"""Generate the Edmonton bridge models (glTF ModelLib) and the placement XML.

Run (from the repo root):   python -I scenery-edmonton-bridges/tools/gen_bridges.py [site ...] [--preview DIR]
Sites are the module names without the `site_` prefix (r10, r9 ...); none given = all.  Needs only the standard library, plus
numpy and Pillow for --preview.

Each site module's build() returns {code, title, lat0, lon0, alt, parts: [(model name, BMesh)]}.  Models are placed at (lat0,
lon0) with heading 0 and an absolute altitude (alt = the site datum, the 2018 LiDAR river surface).  Placements are cached per
site in tools/placements.json, so a run of one site keeps the others, and are written between the BEGIN/END markers of
PackageSources/Scenery/edmonton-bridges/edmonton-bridges.xml.
"""
import importlib, json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bridgelib import ROOT, save_chunks, write_palette, preview  # noqa: E402

CACHE = Path(__file__).resolve().parent / "placements.json"
SCENERY = ROOT / "scenery-edmonton-bridges/PackageSources/Scenery/edmonton-bridges/edmonton-bridges.xml"
BEGIN = "<!-- BEGIN bridges (generated by scenery-edmonton-bridges/tools/gen_bridges.py) -->"
END = "<!-- END bridges -->"
ORDER = ["r10", "r9", "r11", "r15", "r13", "r12", "n258", "n259", "n260", "f256", "b255", "v257", "r14", "p152", "b254", "r20", "r21", "r22", "r6", "w85"]
VIEWS = [("a", 205.0, 20.0), ("b", 120.0, 24.0), ("c", 20.0, 55.0)]


def main(argv):
    pv = None
    if "--preview" in argv:
        i = argv.index("--preview")
        pv = Path(argv[i + 1])
        argv = argv[:i] + argv[i + 2:]
        pv.mkdir(parents=True, exist_ok=True)
    sites = argv or ORDER
    write_palette()
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    for name in ORDER:
        if name not in sites:
            continue
        try:
            mod = importlib.import_module("site_" + name)
        except ModuleNotFoundError as e:
            if e.name == "site_" + name:
                print("skip", name, "(no module)")
                continue
            raise
        res = mod.build()
        cache[name] = {}
        for model_name, mesh in res["parts"]:
            n_poly = len(mesh.pstart)
            if pv:
                for tag, az, el in res.get("views", VIEWS):
                    preview(mesh, pv / f"{model_name}_{tag}.png", az=az, el=el, **res.get("preview", {}))
            made = save_chunks(mesh, model_name)
            print("%-24s %6d polys, %2d chunk(s)" % (model_name, n_poly, len(made)))
            cache[name][model_name] = [(f"{res['code']} {res['title']} ({nm})", res["lat0"], res["lon0"], res["alt"], guid)
                                       for nm, guid in made]
    CACHE.write_text(json.dumps(cache, indent=1), encoding="utf-8")
    lines = ["\t" + BEGIN]
    n = 0
    for name in ORDER:
        for parts in cache.get(name, {}).values():
            for title, lat, lon, alt, guid in parts:
                lines.append("\t<!-- %s -->" % title)
                lines.append('\t<SceneryObject lat="%.8f" lon="%.8f" alt="%.3f" pitch="0.000000" bank="0.000000" heading="0.000000" '
                             'imageComplexity="VERY_SPARSE" altitudeIsAgl="FALSE" snapToGround="FALSE" snapToNormal="FALSE">'
                             % (lat, lon, alt))
                lines.append('\t\t<LibraryObject name="%s" scale="1.000000"/>' % guid)
                lines.append("\t</SceneryObject>")
                n += 1
    lines.append("\t" + END)
    xml = SCENERY.read_text(encoding="utf-8")
    block = "\n".join(lines) + "\n"
    if BEGIN in xml:
        xml = re.sub(r"\t" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _m: block, xml, flags=re.S)
    else:
        xml = re.sub(r"\t<!-- Bridge placements go here[^\n]*\n", "", xml).replace("</FSData>", block + "</FSData>")
    SCENERY.write_text(xml, encoding="utf-8")
    print(n, "placements written")


if __name__ == "__main__":
    main(sys.argv[1:])
