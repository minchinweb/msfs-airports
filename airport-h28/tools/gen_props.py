"""Generate the H28 road props as flat-colour glTF models, and place them in H28.xml between BEGIN/END markers:
  h28_barrel   orange-and-white traffic drum with a black base (Canadian side: the lane divider in front of the CBSA
               office, where the 2025 Street View shows tall delineators and drums; all of them are drums here)
  h28_jersey   12.5 ft concrete Jersey barrier (US side, along the CBP inspection lane)
Run gen_port.py first (it owns the palette), then:
    python -I airport-h28/tools/gen_props.py
Positions: the CBSA divider follows OSM way 1147664053 (barrier=bollard). The Jersey barrier row is an estimate: the west
edge of the grass island between the CBP inspection lane and the through road (OSM ways 1147664050 and 595429620); no
photo in the repo shows them, so move JERSEY_ROW if they sit elsewhere."""
import math
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_field as gf  # noqa: E402
import gen_port as gp  # noqa: E402

LAT, LON = gp.LAT, gp.LON
BEGIN = "<!-- BEGIN road props (generated by airport-h28/tools/gen_props.py) -->"
END = "<!-- END road props -->"
DIVIDER = [(48.999080, -112.788355), (48.999284, -112.788186), (48.999332, -112.788155), (48.999388, -112.788135),
           (48.999430, -112.788133), (48.999628, -112.788133)]  # OSM way 1147664053
BARREL_GAP = 5.0
EXTRA_BARRELS = [(48.999060, -112.788370), (48.999050, -112.788345), (48.999650, -112.788120)]  # ends of the divider
JERSEY_LEN = 12.5 * 0.3048
JERSEY_ROW = ((48.99640, -112.78855), (48.99712, -112.78855))  # S to N


def face(m, pts, sw, centre):
    """Polygon wound so its normal points away from centre (the model's inside)."""
    a, b, c = pts[0], pts[1], pts[2]
    u = [b[i] - a[i] for i in range(3)]
    v = [c[i] - a[i] for i in range(3)]
    n = (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
    p = [sum(q[i] for q in pts) / len(pts) - centre[i] for i in range(3)]
    m.poly(pts if sum(n[i] * p[i] for i in range(3)) >= 0 else pts[::-1], sw)


def drum(m, r0, r1, y0, y1, sw, n=16):
    c = (0.0, (y0 + y1) / 2, 0.0)
    for i in range(n):
        a0, a1 = 2 * math.pi * i / n, 2 * math.pi * (i + 1) / n
        face(m, [(r0 * math.cos(a0), y0, r0 * math.sin(a0)), (r0 * math.cos(a1), y0, r0 * math.sin(a1)),
                 (r1 * math.cos(a1), y1, r1 * math.sin(a1)), (r1 * math.cos(a0), y1, r1 * math.sin(a0))], sw, c)


def barrel():
    """Traffic drum: black base ring, then orange / white / orange / white / orange bands, orange top (about 0.95 m)."""
    m = gp.Mesh()
    drum(m, 0.40, 0.40, 0.0, 0.07, gp.DARK)
    m.poly([(0.40 * math.cos(2 * math.pi * i / 16), 0.07, 0.40 * math.sin(2 * math.pi * i / 16)) for i in range(16)][::-1],
           gp.DARK)  # base ring top
    y, h = 0.07, 0.176
    for k, sw in enumerate((gp.ORANGE, gp.WHITE, gp.ORANGE, gp.WHITE, gp.ORANGE)):
        drum(m, 0.29 - 0.006 * k, 0.29 - 0.006 * (k + 1), y, y + h, sw)
        y += h
    rt = 0.29 - 0.006 * 5
    m.poly([(rt * math.cos(2 * math.pi * i / 16), y, rt * math.sin(2 * math.pi * i / 16)) for i in range(16)][::-1], gp.ORANGE)
    return m


def jersey():
    """New Jersey profile (32 in tall, 24 in base, 6 in top: 3 in toe, 55 deg face to 13 in, then 84 deg), extruded
    along +Z for JERSEY_LEN."""
    m = gp.Mesh()
    prof = [(0.305, 0.0), (0.305, 0.076), (0.127, 0.33), (0.076, 0.81)]
    L = JERSEY_LEN
    c = (0.0, 0.35, L / 2)
    for sgn in (1, -1):
        for (xa, ya), (xb, yb) in zip(prof, prof[1:]):
            face(m, [(sgn * xa, ya, 0.0), (sgn * xa, ya, L), (sgn * xb, yb, L), (sgn * xb, yb, 0.0)], gp.GREY, c)
    face(m, [(-0.076, 0.81, 0.0), (0.076, 0.81, 0.0), (0.076, 0.81, L), (-0.076, 0.81, L)], gp.GREY, c)
    # the end profile is concave at the slope break, so cap it as two convex pieces (poly() fans from vertex 0)
    lower = prof[:3] + [(-x, y) for x, y in reversed(prof[:3])]
    upper = prof[2:] + [(-x, y) for x, y in reversed(prof[2:])]
    for z in (0.0, L):
        for piece in (lower, upper):
            face(m, [(x, y, z) for x, y in piece], gp.GREY, c)
    return m


def along(pts, gap):
    """Points every gap metres along a polyline (lat, lon), starting at its first vertex."""
    out, carry = [], 0.0
    for (la0, lo0), (la1, lo1) in zip(pts, pts[1:]):
        seg = math.hypot((lo1 - lo0) * LON, (la1 - la0) * LAT)
        t = carry
        while t <= seg:
            f = t / seg
            out.append((la0 + f * (la1 - la0), lo0 + f * (lo1 - lo0)))
            t += gap
        carry = t - seg
    return out


def main():
    ml = gp.MODELLIB
    g_barrel = barrel().save(ml / "h28_barrel", "h28_barrel")
    g_jersey = jersey().save(ml / "h28_jersey", "h28_jersey")
    out = [f"\t{BEGIN}\n"]
    for la, lo in along(DIVIDER, BARREL_GAP) + EXTRA_BARRELS:
        out.append(gf.obj("traffic drum, CBSA lane divider", g_barrel, la, lo))
    (la0, lo0), (la1, lo1) = JERSEY_ROW
    length = math.hypot((lo1 - lo0) * LON, (la1 - la0) * LAT)
    hd = math.degrees(math.atan2((lo1 - lo0) * LON, (la1 - la0) * LAT)) % 360
    n = int(length // (JERSEY_LEN + 0.05))
    for k in range(n):
        f = k * (JERSEY_LEN + 0.05) / length
        out.append(gf.obj("Jersey barrier, CBP inspection lane", g_jersey, la0 + f * (la1 - la0), lo0 + f * (lo1 - lo0), hd))
    out.append(f"\t{END}\n")
    block = "".join(out)
    s = gp.H28.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in s else "\n"
    s = s.replace("\r\n", "\n")
    if BEGIN in s:
        s = re.sub(r"\t" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _m: block, s, flags=re.S)
    else:
        i = s.index("\t<Airport displayName")
        s = s[:i] + block + s[i:]
    gp.H28.write_text(s.replace("\n", nl), encoding="utf-8", newline="")
    print(block.count("traffic drum"), "drums,", n, "Jersey barriers")


if __name__ == "__main__":
    main()
