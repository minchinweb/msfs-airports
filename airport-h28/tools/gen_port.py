def write_palette(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    w, h = SW * len(PALETTE), SW
    raw = b"".join(b"\x00" + b"".join(bytes(PALETTE[x // SW]) for x in range(w)) for _ in range(h))

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) \
        + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.write_bytes(png)
    path.with_name(path.name + ".xml").write_text(
        '<BitmapConfiguration>\n\t<BitmapSlot>MTL_BITMAP_DECAL0</BitmapSlot>\n</BitmapConfiguration>\n')


class Mesh:
    def __init__(self):
        self.pos, self.nrm, self.uv, self.idx, self.glow = [], [], [], [], []
        self.lights = []  # (x, y, z, intensity, cone angle, flare only) street lights, model frame before mirroring

    def poly(self, pts, sw, glow=False):
        """Flat polygon, normal from the winding (counter-clockwise seen from outside)."""
        a, b, c = pts[0], pts[1], pts[2]
        u = [b[i] - a[i] for i in range(3)]
        v = [c[i] - a[i] for i in range(3)]
        n = (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
        ln = math.sqrt(sum(x * x for x in n)) or 1.0
        n = tuple(x / ln for x in n)
        base = len(self.pos)
        uv = ((sw + 0.5) / len(PALETTE), 0.5)
        for p in pts:
            self.pos.append(p)
            self.nrm.append(n)
            self.uv.append(uv)
        for i in range(1, len(pts) - 1):
            self.idx += [base, base + i, base + i + 1]
            self.glow.append(glow)

    def box(self, x0, x1, y0, y1, z0, z1, sw, top=True, bottom=False):
        P = lambda x, y, z: (x, y, z)  # noqa: E731
        self.poly([P(x0, y0, z1), P(x1, y0, z1), P(x1, y1, z1), P(x0, y1, z1)], sw)  # north
        self.poly([P(x1, y0, z0), P(x0, y0, z0), P(x0, y1, z0), P(x1, y1, z0)], sw)  # south
        self.poly([P(x1, y0, z1), P(x1, y0, z0), P(x1, y1, z0), P(x1, y1, z1)], sw)  # east
        self.poly([P(x0, y0, z0), P(x0, y0, z1), P(x0, y1, z1), P(x0, y1, z0)], sw)  # west
        if top:
            self.poly([P(x0, y1, z1), P(x1, y1, z1), P(x1, y1, z0), P(x0, y1, z0)], sw)
        if bottom:
            self.poly([P(x0, y0, z0), P(x1, y0, z0), P(x1, y0, z1), P(x0, y0, z1)], sw)

    def gable(self, x0, x1, y0, rise, z0, z1, sw_roof, sw_wall):
        """Roof on a box top at y0 with the ridge running east-west."""
        P = lambda x, y, z: (x, y, z)  # noqa: E731
        zm, yr = (z0 + z1) / 2, y0 + rise
        self.poly([P(x0, y0, z1), P(x1, y0, z1), P(x1, yr, zm), P(x0, yr, zm)], sw_roof)
        self.poly([P(x1, y0, z0), P(x0, y0, z0), P(x0, yr, zm), P(x1, yr, zm)], sw_roof)
        self.poly([P(x0, y0, z0), P(x0, y0, z1), P(x0, yr, zm)], sw_wall)
        self.poly([P(x1, y0, z1), P(x1, y0, z0), P(x1, yr, zm)], sw_wall)

    def windows(self, x0, x1, z0, z1, y0, y1, count_x, count_z):
        """Lit windows (emissive) on the four walls, slightly proud of the wall."""
        e = 0.04
        P = lambda x, y, z: (x, y, z)  # noqa: E731
        for k in range(count_x):
            w = (x1 - x0) / count_x
            a = x0 + w * (k + 0.25)
            b = a + w * 0.5
            self.poly([P(a, y0, z1 + e), P(b, y0, z1 + e), P(b, y1, z1 + e), P(a, y1, z1 + e)], GLOW, True)
            self.poly([P(b, y0, z0 - e), P(a, y0, z0 - e), P(a, y1, z0 - e), P(b, y1, z0 - e)], GLOW, True)
        for k in range(count_z):
            w = (z1 - z0) / count_z
            a = z0 + w * (k + 0.25)
            b = a + w * 0.5
            self.poly([P(x1 + e, y0, b), P(x1 + e, y0, a), P(x1 + e, y1, a), P(x1 + e, y1, b)], GLOW, True)
            self.poly([P(x0 - e, y0, a), P(x0 - e, y0, b), P(x0 - e, y1, b), P(x0 - e, y1, a)], GLOW, True)

    def poly_out(self, pts, sw, out, glow=False):
        """Polygon turned to face the direction `out`."""
        a, b, c = pts[0], pts[1], pts[2]
        u = [b[i] - a[i] for i in range(3)]
        v = [c[i] - a[i] for i in range(3)]
        n = (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
        self.poly(pts if sum(n[i] * out[i] for i in range(3)) >= 0 else pts[::-1], sw, glow)

    def strut(self, p0, p1, r, sw):
        """Square bar of half-width r from p0 to p1 (lattice members, trim along a slope)."""
        d = [p1[i] - p0[i] for i in range(3)]
        ln = math.sqrt(sum(x * x for x in d))
        d = [x / ln for x in d]
        ref = (0.0, 1.0, 0.0) if abs(d[1]) < 0.9 else (1.0, 0.0, 0.0)
        u = (d[1] * ref[2] - d[2] * ref[1], d[2] * ref[0] - d[0] * ref[2], d[0] * ref[1] - d[1] * ref[0])
        lu = math.sqrt(sum(x * x for x in u))
        u = [x / lu for x in u]
        v = (d[1] * u[2] - d[2] * u[1], d[2] * u[0] - d[0] * u[2], d[0] * u[1] - d[1] * u[0])
        corners = [(1, 1), (-1, 1), (-1, -1), (1, -1)]
        off = [tuple(r * (su * u[i] + sv * v[i]) for i in range(3)) for su, sv in corners]
        for k in range(4):
            o0, o1 = off[k], off[(k + 1) % 4]
            out = tuple(o0[i] + o1[i] for i in range(3))
            self.poly_out([tuple(p0[i] + o0[i] for i in range(3)), tuple(p0[i] + o1[i] for i in range(3)),
                           tuple(p1[i] + o1[i] for i in range(3)), tuple(p1[i] + o0[i] for i in range(3))], sw, out)

    def gable_ns(self, x0, x1, y0, rise, z0, z1, sw_roof, sw_gable):
        """Roof on a box top at y0 with the ridge running north-south; gable ends face north and south."""
        xm, yr = (x0 + x1) / 2, y0 + rise
        self.poly_out([(x0, y0, z0), (x0, y0, z1), (xm, yr, z1), (xm, yr, z0)], sw_roof, (-rise, xm - x0, 0))
        self.poly_out([(x1, y0, z0), (x1, y0, z1), (xm, yr, z1), (xm, yr, z0)], sw_roof, (rise, x1 - xm, 0))
        self.poly_out([(x0, y0, z0), (x1, y0, z0), (xm, yr, z0)], sw_gable, (0, 0, -1))
        self.poly_out([(x0, y0, z1), (x1, y0, z1), (xm, yr, z1)], sw_gable, (0, 0, 1))
        self.poly_out([(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)], sw_roof, (0, -1, 0))

    def panel(self, face, a0, a1, y0, y1, off, sw, glow=False):
        """Rectangle on a wall. face = (origin, along, out): origin on the wall plane, along = unit vector across the
        wall (horizontal), out = the wall's outward normal; a0..a1 along the wall, y0..y1 up, `off` metres proud."""
        o, t, n = face
        P = lambda a, y: tuple(o[i] + t[i] * a + n[i] * off + (y if i == 1 else 0.0) for i in range(3))  # noqa: E731
        self.poly_out([P(a0, y0), P(a1, y0), P(a1, y1), P(a0, y1)], sw, n, glow)
        if off > 0.02:  # reveal round a proud panel
            B = lambda a, y: tuple(o[i] + t[i] * a + (y if i == 1 else 0.0) for i in range(3))  # noqa: E731
            for a, out in ((a0, tuple(-x for x in t)), (a1, t)):
                self.poly_out([B(a, y0), P(a, y0), P(a, y1), B(a, y1)], sw, out)
            self.poly_out([B(a0, y1), B(a1, y1), P(a1, y1), P(a0, y1)], sw, (0, 1, 0))
            self.poly_out([B(a0, y0), B(a1, y0), P(a1, y0), P(a0, y0)], sw, (0, -1, 0))

    def window(self, face, a0, a1, y0, y1, frame=WHITE, panes=1):
        """Framed lit window with a sill; vertical mullions for panes > 1."""
        self.panel(face, a0 - 0.08, a1 + 0.08, y0 - 0.08, y1 + 0.08, 0.03, frame)
        self.panel(face, a0, a1, y0, y1, 0.05, GLOW, True)
        for k in range(1, panes):
            a = a0 + (a1 - a0) * k / panes
            self.panel(face, a - 0.04, a + 0.04, y0, y1, 0.07, frame)
        self.panel(face, a0 - 0.12, a1 + 0.12, y0 - 0.14, y0 - 0.06, 0.09, frame)  # sill

    def door(self, face, a0, a1, h=2.1, sw=WHITE, lite=True):
        self.panel(face, a0 - 0.08, a1 + 0.08, 0.0, h + 0.08, 0.03, TRIM)
        self.panel(face, a0, a1, 0.0, h, 0.05, sw)
        if lite:
            self.panel(face, a0 + 0.2, a1 - 0.2, h * 0.6, h * 0.9, 0.06, GLOW, True)

    def garage_door(self, face, a0, a1, h=2.3, sw=WHITE):
        """Sectional garage door: frame, panel and four horizontal grooves."""
        self.panel(face, a0 - 0.12, a1 + 0.12, 0.0, h + 0.12, 0.03, TRIM)
        self.panel(face, a0, a1, 0.0, h, 0.05, sw)
        for k in range(1, 4):
            y = h * k / 4
            self.panel(face, a0 + 0.05, a1 - 0.05, y - 0.03, y + 0.03, 0.065, GREY)

    def mirror_x(self):
        self.lights = [(-x, *rest) for x, *rest in self.lights]
        self.pos = [(-x, y, z) for x, y, z in self.pos]
        self.nrm = [(-x, y, z) for x, y, z in self.nrm]
        self.idx = [i for t in range(0, len(self.idx), 3) for i in (self.idx[t], self.idx[t + 2], self.idx[t + 1])]

    def save(self, folder, name):
        self.mirror_x()
        folder.mkdir(parents=True, exist_ok=True)
        n = len(self.pos)
        assert n < 65535
        pos = b"".join(struct.pack("<3f", *p) for p in self.pos)
        nrm = b"".join(struct.pack("<3f", *p) for p in self.nrm)
        uv = b"".join(struct.pack("<2f", *p) for p in self.uv)
        blob = pos + nrm + uv
        views = [{"buffer": 0, "byteOffset": 0, "byteLength": len(pos)},
                 {"buffer": 0, "byteOffset": len(pos), "byteLength": len(nrm)},
                 {"buffer": 0, "byteOffset": len(pos) + len(nrm), "byteLength": len(uv)}]
        mn = [min(p[i] for p in self.pos) for i in range(3)]
        mx = [max(p[i] for p in self.pos) for i in range(3)]
        accs = [{"bufferView": 0, "componentType": 5126, "count": n, "type": "VEC3", "min": mn, "max": mx},
                {"bufferView": 1, "componentType": 5126, "count": n, "type": "VEC3"},
                {"bufferView": 2, "componentType": 5126, "count": n, "type": "VEC2"}]
        prims, mats = [], []
        for mi, glow in enumerate((False, True)):
            tris = [self.idx[3 * t:3 * t + 3] for t in range(len(self.glow)) if self.glow[t] == glow]
            if not tris:
                continue
            ib = b"".join(struct.pack("<H", i) for tri in tris for i in tri)
            views.append({"buffer": 0, "byteOffset": len(blob), "byteLength": len(ib)})
            blob += ib
            if len(blob) % 4:
                blob += b"\x00" * (4 - len(blob) % 4)
            accs.append({"bufferView": len(views) - 1, "componentType": 5123, "count": len(tris) * 3, "type": "SCALAR"})
            m = {"name": "h28_glow" if glow else "h28_flat",
                 "pbrMetallicRoughness": {"baseColorTexture": {"index": 0}, "metallicFactor": 0.0, "roughnessFactor": 0.9}}
            if glow:
                m["emissiveFactor"] = [1.0, 1.0, 1.0]
