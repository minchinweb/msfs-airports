def font(name, size):
    return ImageFont.truetype(str(FONTS / name), size)


def text_box(img, text, box, fnt, fill, outline=None, shadow=None, rotate=False):
    """Paint `text` stretched to fill box = (x0, y0, x1, y1). rotate: reads bottom to top (turned 90 deg left)."""
    probe = Image.new("L", (int(fnt.getlength(text)) + 100, fnt.size * 2), 0)
    ImageDraw.Draw(probe).text((50, fnt.size // 4), text, font=fnt, fill=255)
    probe = probe.crop(probe.getbbox())
    if rotate:
        probe = probe.transpose(Image.Transpose.ROTATE_90)
    x0, y0, x1, y1 = (int(round(v)) for v in box)
    mask = probe.resize((x1 - x0, y1 - y0), Image.Resampling.LANCZOS)
    if shadow:
        img.paste(Image.new("RGB", mask.size, shadow[0]), (x0 + shadow[1], y0 + shadow[1]), mask.point(lambda v: v * 6 // 10))
    if outline:
        grown = mask.filter(ImageFilter.MaxFilter(outline[1]))
        img.paste(Image.new("RGB", mask.size, outline[0]), (x0, y0), grown)
    img.paste(Image.new("RGB", mask.size, fill), (x0, y0), mask)


def aggregate(w, h, base, rnd, pebbles=True):
    """Exposed-aggregate concrete, or (pebbles False) weathered paint over concrete."""
    im = Image.new("RGB", (w, h), base)
    if pebbles:
        for colour, n in (((150, 132, 110), 1800), ((110, 96, 84), 900), ((236, 228, 210), 900), ((176, 120, 84), 300)):
            gs.speckle(im, rnd, n, colour, (0.8, 2.6))
    else:
        gs.speckle(im, rnd, 900, tuple(max(0, v - 26) for v in base), (0.8, 3))
        gs.speckle(im, rnd, 200, (200, 196, 184), (1, 4))  # paint flaked off to the concrete
    return im.filter(ImageFilter.GaussianBlur(0.6))


def monument_face(region, painted, lettered, rnd):
    w, h = region[2], region[3]
    im = aggregate(w, h, OCHRE if painted else CREAM, rnd, pebbles=not painted)
    if lettered:
        # the face is a trapezoid stretched over this box, narrowing toward the top: keep the lettering central and low
        x0, x1, y0, y1 = w * 0.36, w * 0.64, h * 0.30, h * 0.86
        if painted:  # pale strip behind the letters (landingaday photo)
            ImageDraw.Draw(im).rectangle([x0 - w * 0.05, y0 - h * 0.02, x1 + w * 0.05, y1 + h * 0.02], fill=(222, 218, 204))
        text_box(im, "INTERNATIONAL  BOUNDARY", (x0, y0, x1, y1), font("arial.ttf", 200), (52, 48, 44), rotate=True)
    return im


def slab_top(region, number, rnd):
    w, h = region[2], region[3]
    im = gs.concrete(w, h, rnd)
    # stamped number on the east edge (the bottom of the region), shadowed letters
    text_box(im, number, (w * 0.30, h * 0.80, w * 0.70, h * 0.92), font("arialbd.ttf", 200), (150, 144, 128),
             shadow=((96, 92, 84), 2))
    return im


def seal(d, cx, cy, r):
    """A simplified CBP seal: white ring, navy disc, white eagle shape."""
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(240, 240, 240))
    r2 = r * 0.86
    d.ellipse([cx - r2, cy - r2, cx + r2, cy + r2], fill=(22, 44, 96))
    r3 = r * 0.62
    d.ellipse([cx - r3, cy - r3, cx + r3, cy + r3], fill=(230, 230, 236))
    s = r * 0.5
    eagle = [(-1.0, -0.2), (-0.4, -0.5), (0, -0.9), (0.4, -0.5), (1.0, -0.2), (0.45, 0.1), (0.3, 0.7), (0, 0.9),
             (-0.3, 0.7), (-0.45, 0.1)]
    d.polygon([(cx + x * s, cy + y * s) for x, y in eagle], fill=(120, 96, 52))


def cbp_front(rnd, ss=2):
    w, h = CBP_FRONT[2] * ss, CBP_FRONT[3] * ss
    im = Image.new("RGB", (w, h), CBP_BLUE)
    d = ImageDraw.Draw(im)
    B = lambda nx0, ny0, nx1, ny1: (nx0 * w, ny0 * h, nx1 * w, ny1 * h)  # noqa: E731
    white = (246, 246, 246)
    seal(d, 0.124 * w, 0.20 * h, 0.075 * w)
    serif = font("georgia.ttf", 200)
    text_box(im, "U.S. Customs and Border Protection", B(0.23, 0.13, 0.89, 0.23), serif, white)
    text_box(im, "Port of Del Bonita, Montana", B(0.24, 0.27, 0.71, 0.36), serif, white)
    text_box(im, "CBP CLEARANCE", B(0.32, 0.45, 0.79, 0.55), font("arialbd.ttf", 200), white)
    # arrow pointing left
    ax0, ax1, ay = 0.39 * w, 0.62 * w, 0.655 * h
    d.rectangle([ax0 + 0.05 * w, ay - 0.018 * h, ax1, ay + 0.018 * h], fill=white)
    d.polygon([(ax0, ay), (ax0 + 0.06 * w, ay - 0.06 * h), (ax0 + 0.06 * w, ay + 0.06 * h)], fill=white)
    # white-bordered box
    d.rectangle(B(0.04, 0.77, 0.97, 0.97), outline=white, width=int(0.012 * h))
    text_box(im, "Stay in Plane Until Officer Arrives", B(0.075, 0.81, 0.935, 0.92), font("arialbd.ttf", 200), white)
    # thin white edge, as on most federal signs
    d.rectangle([0, 0, w - 1, h - 1], outline=(220, 226, 236), width=int(0.01 * h))
    gs.speckle(im, rnd, 300, (60, 116, 190), (1, 3))  # weathering
    return im.resize((CBP_FRONT[2], CBP_FRONT[3]), Image.Resampling.LANCZOS)


def board_face(rnd, ss=2):
    w, h = BOARD[2] * ss, BOARD[3] * ss
    im = Image.new("RGB", (w, h))
    planks = 4
    for k in range(planks):  # horizontal planks, each a slightly different shade, with dark gaps
        k_shade = rnd.randint(-10, 10)
        shade = tuple(v + k_shade for v in BOARD_WOOD)
        y0, y1 = k * h // planks, (k + 1) * h // planks
        im.paste(gs.wood(w, y1 - y0, shade, rnd, streaks=900, spread=16), (0, y0))
        ImageDraw.Draw(im).line([(0, y1 - 1), (w, y1 - 1)], fill=(40, 32, 26), width=4)
    d = ImageDraw.Draw(im)
    bw = int(0.075 * w)  # darker vertical battens at both ends, with nail heads
    for x0 in (0, w - bw):
        im.paste(gs.wood(bw, h, (70, 56, 46), rnd, vertical=True, streaks=300, spread=10), (x0, 0))
        for k in range(14):
            y = (k + 0.5) * h / 14
            cx = x0 + bw / 2 + rnd.uniform(-4, 4)
            d.ellipse([cx - 6, y - 6, cx + 6, y + 6], fill=(150, 140, 128))
    hand = font("segoeprb.ttf", 200)
    outline = ((70, 50, 30), 5)
    text_box(im, "FRANK WHETSTONE", (0.16 * w, 0.09 * h, 0.85 * w, 0.23 * h), hand, LETTER_YELLOW, outline)
    text_box(im, "INTERNATIONAL", (0.14 * w, 0.38 * h, 0.83 * w, 0.59 * h), hand, LETTER_YELLOW, outline)
    text_box(im, "AIRPORT", (0.26 * w, 0.67 * h, 0.70 * w, 0.86 * h), hand, LETTER_YELLOW, outline)
    return im.resize((BOARD[2], BOARD[3]), Image.Resampling.LANCZOS)


def flat(region, colour, rnd, n=400, spread=10):
    im = Image.new("RGB", region[2:], colour)
    gs.speckle(im, rnd, n, tuple(max(0, min(255, v + rnd.choice((-spread, spread)))) for v in colour), (0.8, 3))
    return im.filter(ImageFilter.GaussianBlur(0.8))


def pipe_tile(region):
    w, h = region[2:]
    im = Image.new("RGB", (w, h))
    d = ImageDraw.Draw(im)
    for x in range(w):  # vertical shading band, so a pipe face reads as round
        v = int(150 + 50 * math.sin(math.pi * x / w))
        d.line([(x, 0), (x, h)], fill=(v, v + 2, v + 4))
    return im


def write_texture(path):
    rnd = random.Random(308)
    im = Image.new("RGB", (gs.A, gs.A), (0, 0, 0))
    put = lambda region, tile: im.paste(tile, region[:2])  # noqa: E731
    put(CBP_FRONT, cbp_front(rnd))
    put(BOARD, board_face(rnd))
    put(MON_A_TEXT, monument_face(MON_A_TEXT, False, True, rnd))
    put(MON_A_PLAIN, monument_face(MON_A_PLAIN, False, False, rnd))
    put(MON_B_TEXT, monument_face(MON_B_TEXT, True, True, rnd))
    put(MON_B_PLAIN, monument_face(MON_B_PLAIN, True, False, rnd))
    put(SLAB_A, slab_top(SLAB_A, "308A", rnd))
    put(SLAB_B, slab_top(SLAB_B, "308B", rnd))
    put(CONCRETE, gs.concrete(CONCRETE[2], CONCRETE[3], rnd))
    put(ALUMINIUM, flat(ALUMINIUM, (176, 180, 184), rnd))
    put(POST, gs.wood(POST[2], POST[3], (112, 96, 80), rnd, vertical=True, streaks=1200, spread=14))
    put(PIPE, pipe_tile(PIPE))
    put(BALL, flat(BALL, (214, 96, 52), rnd, n=600, spread=16))
    put(WOOD, gs.wood(WOOD[2], WOOD[3], BOARD_WOOD, rnd, streaks=500, spread=14))
    put(BOLT, flat(BOLT, (90, 86, 82), rnd))
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, optimize=True)
    path.with_name(path.name + ".xml").write_text(
        '<BitmapConfiguration>\n\t<BitmapSlot>MTL_BITMAP_DECAL0</BitmapSlot>\n</BitmapConfiguration>\n')


