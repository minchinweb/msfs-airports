"""Adds the two International Boundary Commission obelisks at the crossing (MON 308A and 308B) and the two signs just
inside the strip's west fence: the "Frank Whetstone International Airport" board and the blue CBP clearance sign.

    python -I airport-h28/tools/gen_border.py

Writes four textured models (h28_mon_308a, h28_mon_308b, h28_sign_whetstone, h28_sign_cbp) sharing one 2048 x 2048
texture, h28_border.png, in modelLib/texture, and their placements between their own BEGIN/END markers in H28.xml. Like
gen_sign.py it uses gen_port.Mesh but not the shared palette, so it can run in any order with the other generators.
Needs Pillow and the Windows fonts Arial Bold, Georgia and Segoe Print Bold.

Model frame (as in gen_sign.py, before Mesh.save mirrors x): x east, y up, z north. Every model is placed at heading 0;
the signs' fronts face east, toward the strip.

Sources (docs/h28/reference/):
- Monument positions: IBC coordinate list, 49th parallel, AB/SK/MB-MT/ND section, NAD83 values ("averaged NADCON/NTV2
  grid shift"): MON 308A N 48 59 54.8 W 112 47 18.5, MON 308B N 48 59 54.8 W 112 47 17.7 (both set in 1945).
  https://www.internationalboundarycommission.org/uploads/maps/21-49th_parallel_prairies/49th%20parallel%20ab_sk_mb-mt_nd%20(english).pdf
  The two stand either side of AB-62, 16.9 m apart. Their midpoint is 3 m east of OSM's road centre (-112.7884), which
  the sim aerial matches, so both are moved 3 m west (ROAD_SHIFT) to keep them on the verges of the sim's road.
- 308A: clui-2014-08-20-02-05-02.jpg (west verge, looking west): cream exposed-aggregate concrete, "INTERNATIONAL
  BOUNDARY" cut in dark letters up the face, small square slab. Shaft about 4.5 x its base width, slab about 1.9 x.
- 308B: landingaday-runway-on-border.jpg (east verge, looking east down the strip; "308B" stamped on the slab, read from
  a blurry photo): the same obelisk painted ochre-yellow with the lettering on a pale strip, on a larger slab (about
  2.9 x the shaft). In clui-2014-08-20-02-06-58.jpg it hides behind the CBP sign.
  Sizes are not measured; the shaft is taken as 0.30 m square at the base.
- Signs: clui-2014-08-20-02-06-58.jpg (from the strip, looking west) and wikimedia-sign-and-runway.jpg (2026, from the
  road, looking east). Scale: the CBP panel taken as 60 x 30 in, which puts the 2014 camera at 1.6 m, eye height.
  - CBP sign: blue aluminium panel on two 4 x 4 wooden posts: seal, "U.S. Customs and Border Protection", "Port of Del
    Bonita, Montana", "CBP CLEARANCE", an arrow pointing left (south), and "Stay in Plane Until Officer Arrives" in a
    white box. Panel 1.27-2.03 m up. Not in the 2026 photo, which is framed further south; it may be gone.
  - Whetstone sign: weathered plank board with yellow hand-lettering (lettered on both sides: both photos show it),
    hung on eye bolts from a galvanized pipe frame (1.30 m between uprights, crossbar 2.0 m up). The old orange marker
    ball on the ground under it (both photos) is left out (user review, 2026-11-07).
  - Two white cones (the strip's edge-cone model) east of the signs, 1.6 m apart north-south: in front of the signs in
    the 2014 photo and, in the 2026 photo, beyond the board seen from the road. Their 0.9 m base agrees with the CBP
    panel scale.
  - Position: both just inside the west fence (the 2026 photo shows the board about 2 m behind the road fence), the CBP
    sign by the border and the Whetstone board about 3 m south of it (left of it in the 2014 photo). Estimated, not
    measured.
"""

