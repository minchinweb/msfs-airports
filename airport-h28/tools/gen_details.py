"""Adds the small textured details at the two ports and the border (2026-11-16):

  h28_cbsa_fascia_sign   the dark-green "Del Bonita" band on the south fascia of the CBSA office, over the bay
  h28_cbp_lettering      "U.S. Customs and Border Protection / Del Bonita Port of Entry" on the CBP office gable
  h28_sign_cbsa_report   CBSA "Everyone must report to Border Inspection" roadside sign
  h28_sign_cbsa_border   CBSA "Border Inspection / Controle frontalier / Canada" roadside sign
  h28_gate_border        the two yellow swing gates at the border, standing open on the verges
  h28_cairn              the 1974 RCMP / Alberta centennial stone cairn north of the CBSA annex
  h28_fence_gate         the braced gate posts in the strip's west fence

    python -I airport-h28/tools/gen_details.py

All share one 2048 x 2048 texture, h28_details.png, in modelLib/texture; placements go between this file's own
BEGIN/END markers in H28.xml. Like gen_border.py it uses gen_port.Mesh but not the shared palette. The two wall signs
are placed at their building's origin, so run gen_port.py first if a building moved; otherwise it runs in any order.
Needs Pillow and the Windows fonts Arial, Arial Bold and Georgia.

Sources (docs/h28/reference/ unless noted):
- Fascia sign: mindtrip-02-del-bonita-canopy-building.jpg (the band runs from the west corner to past the bay: arrow,
  two vehicle pictograms, the 3.5 m clearance mark, "Del Bonita") and streetview-2025-09-i. South face only:
  mindtrip-03 shows the north fascia bare.
- CBP lettering: wikimedia-delbonita-usa-2014.jpg (Jan 2014).
- CBSA signs: streetview-2025-09-a and -i. Panel sizes are estimates (2.4 m wide); the wording is as far as it can be
  read. Positions: "report" on the east verge north of the Canadian pocket, "border" on the grass south-west of the
  cream shed. Both face south, to northbound traffic.
- Border gates: streetview-2025-09-f (east verge: the leaf stands open pointing east, in front of monument 308B, with a
  STOP sign and a CLOSED / FERME sign facing north) and -g (west verge: the leaf lies along the road). Yellow tube
  frames with a red-and-white bar. Leaf length (4 m) is an estimate.
- Cairn: mindtrip-03-canadian-buildings-snow.jpg and mindtrip-04-rcmp-cairn-1974.jpg: fieldstone block about 1.3 m wide
  and 1.75 m tall on two concrete steps, concrete cap, bronze plaque on the north face, four posts and a chain round it.
  Position from the Esri clip (docs/h28/esri/cbsa-port.png): about 8 m east and 10.5 m north of the office centre.
- Fence gate: streetview-2025-09-b and -c: weathered H-braces (a tall post, a rail and a shorter post) either side of a
  wire gate in the west fence. Taken to be on the runway centreline; the fence itself is not cut (a closed wire gate).
"""

