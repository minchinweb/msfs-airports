def stripes():
    w, h = STRIPE[2:]
    im = Image.new("RGB", (w, h), WHITE)
    d = ImageDraw.Draw(im)
    for x in range(-h, w, 96):
        d.polygon([(x, h), (x + h, 0), (x + h + 48, 0), (x + 48, h)], fill=(204, 36, 36))
    return im


def fieldstone(rnd):
    w, h = STONE[2:]
    im = Image.new("RGB", (w, h), (92, 84, 78))  # mortar
    d = ImageDraw.Draw(im)
    colours = [(120, 60, 56), (96, 52, 50), (140, 96, 80), (104, 120, 108), (120, 112, 104), (150, 120, 96), (84, 76, 80),
               (132, 150, 138)]
    y = 0
    while y < h:
        rh = rnd.randint(44, 72)
        x = -rnd.randint(0, 40)
        while x < w:
            rw = rnd.randint(50, 110)
            c = rnd.choice(colours)
            d.rounded_rectangle([x + 4, y + 4, x + rw - 4, y + rh - 4], radius=14, fill=c)
            x += rw
        y += rh
    gs.speckle(im, rnd, 2500, (70, 64, 60), (1, 3))
    return im.filter(ImageFilter.GaussianBlur(0.8))


def plaque(rnd):
    w, h = PLAQUE[2:]
    im = Image.new("RGB", (w, h), (58, 50, 42))
    d = ImageDraw.Draw(im)
    d.rectangle([8, 8, w - 9, h - 9], outline=(110, 96, 72), width=4)
    for k in range(9):  # raised lettering, too small to read
        x0 = 30 + (rnd.randint(0, 30) if k else 20)
        d.rectangle([x0, 34 + k * 22, w - 30 - rnd.randint(0, 40), 42 + k * 22], fill=(120, 106, 82))
    return im


def write_texture(path):
    rnd = random.Random(1974)
    im = Image.new("RGB", (gs.A, gs.A), (0, 0, 0))
    put = lambda region, tile: im.paste(tile, region[:2])  # noqa: E731
    put(DELBONITA, delbonita())
    put(CBSA_REPORT, cbsa_report())
    put(CBSA_BORDER, cbsa_border())
    put(CBP_LETTER, cbp_letter())
    put(STOP, stop_face())
    put(CLOSED, closed_face())
    put(STRIPE, stripes())
    put(YELLOW, gb.flat(YELLOW, (226, 186, 40), rnd, n=500, spread=14))
    put(DGREEN, gb.flat(DGREEN, (44, 58, 60), rnd))
    put(STONE, fieldstone(rnd))
    put(PLAQUE, plaque(rnd))
    put(CONC, gs.concrete(CONC[2], CONC[3], rnd))
    put(WOODP, gs.wood(WOODP[2], WOODP[3], (132, 124, 112), rnd, vertical=True, streaks=1200, spread=16))
    put(STEELP, gb.flat(STEELP, (150, 154, 158), rnd))
    put(BACK, gb.flat(BACK, (120, 124, 126), rnd))
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, optimize=True)
    path.with_name(path.name + ".xml").write_text(
        '<BitmapConfiguration>\n\t<BitmapSlot>MTL_BITMAP_DECAL0</BitmapSlot>\n</BitmapConfiguration>\n')


