def delbonita():
    w, h = DELBONITA[2:]
    im = Image.new("RGB", (w, h), SIGN_GREEN)
    d = ImageDraw.Draw(im)
    # arrow pointing down-left
    d.line([(150, 70), (70, 180)], fill=WHITE, width=16)
    d.polygon([(52, 204), (58, 132), (118, 176)], fill=WHITE)
    for x0, long in ((200, True), (370, False)):  # vehicle pictograms: white squares with a dark vehicle
        d.rectangle([x0, 58, x0 + 140, 198], fill=WHITE)
        d.rectangle([x0 + 18, 112, x0 + (122 if long else 96), 150], fill=SIGN_GREEN)
        d.rectangle([x0 + 30, 92, x0 + 80, 114], fill=SIGN_GREEN)
        for cx in (x0 + 40, x0 + (100 if long else 80)):
            d.ellipse([cx - 12, 142, cx + 12, 166], fill=SIGN_GREEN)
    d.rectangle([820, 50, 960, 206], outline=WHITE, width=8)  # clearance mark
    gb.text_box(im, "3.5 m", (838, 66, 942, 110), gb.font("arialbd.ttf", 120), WHITE)
    gb.text_box(im, "11'-6\"", (838, 118, 942, 156), gb.font("arialbd.ttf", 120), WHITE)
    d.polygon([(868, 168), (912, 168), (890, 196)], fill=WHITE)
    gb.text_box(im, "Del Bonita", (1300, 74, 1960, 196), gb.font("arialbd.ttf", 200), WHITE)
    return im


def flag_mark(d, x, y, s):
    """The small Canadian flag symbol of federal signs: red bar, white square with a red block, red bar."""
    d.rectangle([x, y, x + s * 0.5, y + s], fill=(214, 40, 40))
    d.rectangle([x + s * 0.5, y, x + s * 1.5, y + s], fill=WHITE)
    d.rectangle([x + s * 0.8, y + s * 0.25, x + s * 1.2, y + s * 0.75], fill=(214, 40, 40))
    d.rectangle([x + s * 1.5, y, x + s * 2.0, y + s], fill=(214, 40, 40))


def cbsa_report():
    w, h = CBSA_REPORT[2:]
    im = Image.new("RGB", (w, h), CBSA_SLATE)
    d = ImageDraw.Draw(im)
    flag_mark(d, 60, 40, 44)
    small, bold = gb.font("arial.ttf", 120), gb.font("arialbd.ttf", 200)
    for x, lines in ((190, ("Canada Border", "Services Agency")), (600, ("Agence des services", "frontaliers du Canada"))):
        for k, t in enumerate(lines):
            gb.text_box(im, t, (x, 34 + k * 34, x + len(t) * 15, 60 + k * 34), small, WHITE)
    for x, lines in ((190, ("Everyone", "must report", "to Border", "Inspection")),
                     (600, ("Toute personne", "doit se présenter", "au contrôle", "frontalier"))):
        for k, t in enumerate(lines):
            gb.text_box(im, t, (x, 150 + k * 62, x + len(t) * 22, 198 + k * 62), bold, WHITE)
    d.rectangle([92, 330, 112, 450], fill=WHITE)  # arrow up
    d.polygon([(102, 290), (56, 350), (148, 350)], fill=WHITE)
    return im


