def build_fascia_sign():
    """Band on the south fascia of the CBSA office, in the office model's frame (placed at its origin)."""
    w, h = next((f[4], f[6]) for f in gp.FOOTPRINTS if f[0] == "cbsa_main")
    zs = -gp.BLOCK_D / 2 - 0.25  # the fascia's south face
    m = gp.Mesh()
    gs.tbox(m, -w / 2 - 0.27, gp.BAY[1] + 1.4, h - 0.18, h + 0.48, zs - 0.03, zs, BACK, south=DELBONITA, faces="sewt")
    return m


def build_cbp_lettering():
    """Lettering panel on the CBP office's south gable, in the CBP model's frame (gen_port.cbp_port: office x -10.5 to
    -1.5, south wall at z -7.5)."""
    m = gp.Mesh()
    gs.tbox(m, -8.0, -4.0, 2.42, 3.42, -7.53, -7.5, BACK, south=CBP_LETTER, faces="s")
    return m


def build_road_sign(region, height, bottom):
    """Panel 2.4 m wide facing south on two dark posts. Origin on the ground under its middle."""
    m = gp.Mesh()
    top = bottom + height
    for x in (-1.05, 1.05):
        gs.tbox(m, x - 0.05, x + 0.05, -0.3, top, 0.03, 0.13, DGREEN)
    gs.tbox(m, -1.2, 1.2, bottom, top, -0.02, 0.03, DGREEN, south=region)
    gs.quad(m, [(-1.2, bottom, -0.02), (1.2, bottom, -0.02), (1.2, bottom, 0.03), (-1.2, bottom, 0.03)], (0, -1, 0),
            DGREEN, (1, 0, 0), (0, 0, 1))
    return m


def gate_leaf(m, hx, hz, dx, dz, signs):
    """Yellow tube gate leaf 4 m long from its hinge post at (hx, hz), pointing along (dx, dz), with the red-and-white
    bar on top. signs: STOP and CLOSED boards on the leaf's north face (only for a leaf lying east-west)."""
    ln, r = 4.0, 0.04
    ex, ez = hx + dx * ln, hz + dz * ln
    gb.cylinder(m, (hx, -0.3, hz), (hx, 1.5, hz), 0.06, YELLOW)
    gb.cylinder(m, (ex, 0.45, ez), (ex, 1.2, ez), r, YELLOW)
    for y in (0.5, 1.2):
        gb.cylinder(m, (hx, y, hz), (ex, y, ez), r, YELLOW)
    gb.cylinder(m, (hx, 0.5, hz), (ex, 1.2, ez), r * 0.8, YELLOW)  # diagonal brace
    gb.cylinder(m, (hx, 1.45, hz), (hx + dx * ln * 0.55, 1.2, hz + dz * ln * 0.55), r * 0.8, YELLOW)  # stay from the post
    if signs:  # lies east-west: bar and boards as boxes
        gs.tbox(m, min(hx, ex), max(hx, ex), 1.24, 1.38, hz - 0.03, hz + 0.03, STRIPE)
        cx, s, c = hx + dx * 1.1, 0.375, 0.375 * math.tan(math.pi / 8)
        octagon = [(cx - c, 0.95, hz + 0.06), (cx + c, 0.95, hz + 0.06), (cx + s, 0.95 + s - c, hz + 0.06),
                   (cx + s, 0.95 + s + c, hz + 0.06), (cx + c, 0.95 + 2 * s, hz + 0.06), (cx - c, 0.95 + 2 * s, hz + 0.06),
                   (cx - s, 0.95 + s + c, hz + 0.06), (cx - s, 0.95 + s - c, hz + 0.06)]
        gs.quad(m, octagon, (0, 0, 1), STOP, (-1, 0, 0), (0, 1, 0))
        gs.quad(m, octagon, (0, 0, -1), STEELP, (1, 0, 0), (0, 1, 0))
        bx = hx + dx * 2.0
        gs.tbox(m, bx - 0.3, bx + 0.3, 0.95, 1.7, hz + 0.04, hz + 0.06, STEELP, north=CLOSED, faces="ns")
    else:  # bar along the top rail
        gb.cylinder(m, (hx, 1.3, hz), (ex, 1.3, ez), 0.06, STRIPE, n=4)


def build_border_gates():
    """Both leaves in one model (about 14 m across, so the sim does not cull it early). Origin on the road centre."""
    m = gp.Mesh()
    gate_leaf(m, 5.0, 0.0, 1.0, 0.0, True)  # east verge: open, pointing east, in front of monument 308B
    n = math.hypot(-0.25, 1.0)
    gate_leaf(m, -5.0, 0.0, -0.25 / n, 1.0 / n, False)  # west verge: lying along the road, pointing north
    return m


def build_cairn():
    m = gp.Mesh()
    gb.box(m, -1.2, 1.2, -0.2, 0.15, -0.9, 0.9, CONC)
    gb.box(m, -0.85, 0.85, 0.15, 0.3, -0.6, 0.6, CONC)
    gb.box(m, -0.65, 0.65, 0.3, 2.05, -0.4, 0.4, STONE, faces="nsew")
    gb.box(m, -0.72, 0.72, 2.05, 2.2, -0.47, 0.47, CONC)
    gs.quad(m, [(-0.72, 2.05, -0.47), (0.72, 2.05, -0.47), (0.72, 2.05, 0.47), (-0.72, 2.05, 0.47)], (0, -1, 0), CONC,
            (1, 0, 0), (0, 0, 1))
    gs.tbox(m, -0.22, 0.22, 1.15, 1.6, 0.4, 0.42, PLAQUE, faces="n")
    posts = [(-1.15, -0.85), (1.15, -0.85), (1.15, 0.85), (-1.15, 0.85)]
    for k, (x, z) in enumerate(posts):
        gb.cylinder(m, (x, 0.1, z), (x, 0.95, z), 0.03, STEELP, n=6)
        nx, nz = posts[(k + 1) % 4]
        gb.cylinder(m, (x, 0.75, z), (nx, 0.75, nz), 0.015, STEELP, n=4)  # chain
    return m


def build_fence_gate():
    """Two H-braces either side of a 4.6 m wire gate, along the fence (north-south). Origin on the fence line."""
    m = gp.Mesh()
    for s in (-1, 1):
        gb.cylinder(m, (0.0, -0.3, s * 2.3), (0.0, 2.3, s * 2.3), 0.09, WOODP)
        gb.cylinder(m, (0.0, -0.3, s * 4.7), (0.0, 1.5, s * 4.7), 0.07, WOODP)
        gb.cylinder(m, (0.0, 1.25, s * 2.3), (0.0, 1.25, s * 4.7), 0.05, WOODP)
    return m


def save(m, name):
    folder = gp.MODELLIB / name
    guid = m.save(folder, name)
    gltf = folder / f"{name}.gltf"
    g = json.loads(gltf.read_text())
    g["asset"]["generator"] = "airport-h28/tools/gen_details.py"
    g["images"] = [{"uri": f"{TEX}.png"}]
    g["samplers"] = [{"magFilter": 9729, "minFilter": 9987, "wrapS": 33071, "wrapT": 33071}]  # linear, mipmapped
    for mat in g["materials"]:
        mat["name"] = TEX
        mat["pbrMetallicRoughness"]["roughnessFactor"] = 0.85
    gltf.write_text(json.dumps(g, indent=1))
    return guid


def main():
    write_texture(gp.MODELLIB / "texture" / f"{TEX}.png")
    at = {f[0]: (f[2], f[3] + gp.DX) for f in gp.FOOTPRINTS}
    cbsa, cbp = at["cbsa_main"], at["cbp_main"]
    shed4 = at["cbsa_shed4"]
    items = [
        ("h28_cbsa_fascia_sign", build_fascia_sign(), cbsa, '"Del Bonita" band on the CBSA office\'s south fascia (at the office origin)'),
        ("h28_cbp_lettering", build_cbp_lettering(), cbp, "CBP lettering on the office gable (at the CBP building origin)"),
        ("h28_sign_cbsa_report", build_road_sign(CBSA_REPORT, 1.2, 1.3), (48.99898, ROAD_C + 13.0 / gp.LON),
         'CBSA "Everyone must report to Border Inspection" sign, east verge north of the Canadian pocket, facing south'),
        ("h28_sign_cbsa_border", build_road_sign(CBSA_BORDER, 1.8, 0.9), (shed4[0] - 7.0 / gp.LAT, shed4[1] - 5.0 / gp.LON),
         'CBSA "Border Inspection / Canada" sign, on the grass south-west of the cream shed, facing south'),
        ("h28_gate_border", build_border_gates(), (gf.BORDER + 1.5 / gp.LAT, ROAD_C),
         "yellow swing gates at the border, open on both verges (at the road centre, 1.5 m north of the line)"),
        ("h28_cairn", build_cairn(), (cbsa[0] + 10.5 / gp.LAT, cbsa[1] + 8.0 / gp.LON),
         "RCMP / Alberta centennial cairn (1974), north of the CBSA annex"),
        ("h28_fence_gate", build_fence_gate(), (gf.CL, gf.WF), "braced gate posts in the strip's west fence, on the centreline"),
    ]
    parts = [f"\t{BEGIN}\n"]
    for name, mesh, pos, what in items:
        guid = save(mesh, name)
        parts.append(gb.placement(what, guid, *pos))
        print("wrote", name, guid, f"at {pos[0]:.6f}, {pos[1]:.6f}")
    parts.append(f"\t{END}\n")
    block = "".join(parts)
    s = gp.H28.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in s else "\n"
    s = s.replace("\r\n", "\n")
    if BEGIN in s:
        s = re.sub(r"\t" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _m: block, s, flags=re.S)
    else:
        s = s.replace("\t<Airport displayName", block + "\t<Airport displayName", 1)
    gp.H28.write_text(s.replace("\n", nl), encoding="utf-8", newline="")


if __name__ == "__main__":
    main()
