"""Generate the H28 field layout in H28.xml: runway extents and starts, striped-grass aprons, tie-downs and taxi paths,
edge and threshold cones, the perimeter fence (its own glTF segment models), the windsock and the no-vegetation polygon.
    python -I airport-h28/tools/gen_port.py      (palette, buildings)
    python -I airport-h28/tools/gen_cones.py     (cone models)
    python -I airport-h28/tools/gen_field.py
    python -I airport-h28/tools/gen_powerline.py (poles, wires, pole lights)
Safe to re-run: the top-level items sit between BEGIN/END field markers, and the airport's taxi, parking, runway and apron
entries are rewritten in place.

Layout (the sim's aerial matches OSM here; measured 2026-10-28 against Google Earth 2012, OSM way 1208466528 and the AFD):
- Mowed strip fenced 44 ft (13.4 m) each side of the centreline (FAA), full length. The south fence is on the border.
- Runway 65 ft wide on the strip, from the sim default runway's west end (6 m inside the west fence) to its east end.
  That is about 1,595 m; the published 4,440 ft runway is the part between the threshold double cones.
- Threshold double cones (white edge cone plus a red one just outboard of it) 200 m east of the west fence (the red-white
  cones on the 2012 imagery) and 4,440 ft further east; white edge cones evenly spaced (about 200 ft) between them, and
  three more on each edge in the west overrun (as on the 2012 imagery).
- Fenced US parking south of the border at the west end (138 x 77 m), and a small Canadian pocket north of the strip
  (74 m long, out to 24 m north of the centreline)."""
import math
import re
import sys
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_port as gp  # noqa: E402

LAT, LON = gp.LAT, gp.LON
BEGIN = "<!-- BEGIN field layout (generated by airport-h28/tools/gen_field.py) -->"
END = "<!-- END field layout -->"
GRASS = "{322DE917-E25D-4AD8-BFBB-4D5F4D259413}"

CL = 48.99868  # runway centreline (sim default; the user checked it on the aerial)
RW_W, RW_E = -112.788063, -112.766217  # runway ends (sim default runway's ends)
WF = -112.78815  # west fence (OSM fence way 1147679786 and the aerodrome outline), ~17 m east of the road centre
EF = RW_E + 4 / LON  # east fence just past the runway end
NF, SF = CL + 13.4 / LAT, CL - 13.4 / LAT  # strip fences, 44 ft each side
POCKET_N, POCKET_E = 48.99889, WF + 74 / LON  # Canadian parking pocket
PARK_S, PARK_E = 48.99788, WF + 138 / LON  # US parking
BORDER = 48.99857
EDGE = 9.9  # cone line offset (65 ft runway)
T07 = 200.0  # threshold cones, metres east of the west fence
RWY_LEN = 4440 * 0.3048
CONE_SCALE = 2.0
RED_GAP = 2.0  # red threshold cone, metres outboard (along the runway) of the white one, on the same edge line
FENCE_SEG = 20.0  # metres per fence model (at most)
POST_GAP = 5.0


def at(m_east, lat):
    return lat, WF + m_east / LON


def guid(name):
    return "{" + str(uuid.uuid5(gp.NS, name)).upper() + "}"


def obj(title, g, lat, lon, hd=0.0, scale=1.0):
    return (f"\t<!-- {title} -->\n"
            f'\t<SceneryObject lat="{lat:.8f}" lon="{lon:.8f}" alt="0.00000000000000" pitch="0.000000" bank="0.000000" '
            f'heading="{hd:.6f}" imageComplexity="VERY_SPARSE" altitudeIsAgl="TRUE" snapToGround="TRUE" snapToNormal="FALSE">\n'
            f'\t\t<LibraryObject name="{g}" scale="{scale:.6f}"/>\n\t</SceneryObject>\n')


# --- fence -------------------------------------------------------------------------------------------------------------
PERIMETER = [(POCKET_N, WF), (POCKET_N, POCKET_E), (NF, POCKET_E), (NF, EF), (SF, EF), (SF, PARK_E), (PARK_S, PARK_E),
             (PARK_S, WF)]


def fence_model(length):
    """One fence segment along +Z: wooden posts (one at z=0, the next segment supplies the far one), four wire strands."""
    m = gp.Mesh()
    n = max(1, round(length / POST_GAP))
    for k in range(n):
        z = length * k / n
        m.box(-0.06, 0.06, 0.0, 1.3, z - 0.06, z + 0.06, gp.BROWN)
    w = 0.015
    for y in (0.35, 0.6, 0.85, 1.1):
        for quad in ([(-w, y, 0.0), (w, y, 0.0), (w, y, length), (-w, y, length)],
                     [(0.0, y - w, 0.0), (0.0, y + w, 0.0), (0.0, y + w, length), (0.0, y - w, length)]):
            m.poly(quad, gp.DARK)
            m.poly(quad[::-1], gp.DARK)
    return m


def fences():
    out = []
    pts = PERIMETER + PERIMETER[:1]
    for k, ((la0, lo0), (la1, lo1)) in enumerate(zip(pts, pts[1:])):
        de, dn = (lo1 - lo0) * LON, (la1 - la0) * LAT
        length = math.hypot(de, dn)
        hd = math.degrees(math.atan2(de, dn)) % 360
        n = math.ceil(length / FENCE_SEG)
        name = f"h28_fence_{k}"
        g = fence_model(length / n).save(gp.MODELLIB / name, name)
        for i in range(n):
            t = i / n
            out.append(obj(f"fence, edge {k} ({length:.0f} m, heading {hd:.0f}), segment {i + 1}/{n}", g,
                           la0 + t * (la1 - la0), lo0 + t * (lo1 - lo0), hd))
    return out


# --- cones -------------------------------------------------------------------------------------------------------------
def cones():
    """One model per station across the runway (gen_cones.py): the two white edge cones, or at each threshold the
    white and red pair on both edges (heading 0 puts the red cones west, 180 east)."""
    edge, thr = guid("h28_cones_edge"), guid("h28_cones_07")
    n = round(RWY_LEN / 60.96)
    stations = [62.0, 95.0, 127.0] + [T07 + RWY_LEN * k / n for k in range(1, n)]
    out = [obj(f"edge cones, {m:.0f} m from the west fence", edge, *at(m, CL)) for m in stations]
    out.append(obj("threshold 07 cones (red outboard, west)", thr, *at(T07, CL), 0.0))
    out.append(obj("threshold 25 cones (red outboard, east)", thr, *at(T07 + RWY_LEN, CL), 180.0))
    white = guid("h28_cone_white")
    out += [obj(f"west-end cone: {title}", white, *at(m, lat), 0.0, CONE_SCALE) for title, m, lat in WEST_CONES]
    return out


# Single white cones near the west fence, read off the Sep 2025 Street View (docs/h28/reference/streetview-2025-09-*):
# a pair just north of the transformer pole (photos c, d, e; the 2012 imagery has cones there too), one in the US parking
# right of that pole seen from the road (c, e), and one in the Canadian pocket by its north-west corner (a, b).
# Distances come from the cones' apparent sizes against the edge cones at 62/95/127 m, so allow a few metres.
WEST_CONES = [("pair by the transformer pole, north", 32.0, CL - EDGE / LAT),
              ("pair by the transformer pole, south", 32.0, CL - 13.9 / LAT),
              ("US parking, right of the transformer pole from the road", 21.0, BORDER - 13.0 / LAT),
              ("Canadian pocket, by the north-west corner", 3.0, CL + 18.0 / LAT)]


# --- polygons ----------------------------------------------------------------------------------------------------------
def exclusion():
    pad_lat, pad_lon = 2 / LAT, 2 / LON
    west = WF - 12 / LON  # out to the road shoulder
    vs = [(POCKET_N + pad_lat, west), (POCKET_N + pad_lat, POCKET_E + pad_lon), (NF + pad_lat, POCKET_E + pad_lon),
          (NF + pad_lat, EF + pad_lon), (SF - pad_lat, EF + pad_lon), (SF - pad_lat, PARK_E + pad_lon),
          (PARK_S - pad_lat, PARK_E + pad_lon), (PARK_S - pad_lat, west)]
    v = "".join(f'\t\t<Vertex lat="{la:.8f}" lon="{lo:.8f}"/>\n' for la, lo in vs)
    return ('\t<Polygon version="0.5.0" displayName="H28 fenced field: no vegetation or buildings" groupIndex="2" '
            'altitude="1321.59997558593750">\n'
            '\t\t<Attribute name="UniqueGUID" guid="{359C73E8-06BE-4FB2-ABCB-EC942F7761D0}" type="GUID" '
            'value="{6F1D3A52-8B27-4C0E-9A41-5E7B2C9D1A38}"/>\n'
            '\t\t<Attribute name="ExcludeDetectedBuildings" guid="{5C1A2387-1F07-47DF-A569-962CF6258E55}" type="UINT8" value="1"/>\n'
            '\t\t<Attribute name="ExcludeOSMBuildings" guid="{F3C2635D-9F2F-458F-8663-90B3837BED09}" type="UINT8" value="1"/>\n'
            '\t\t<Attribute name="ExcludeMSBuildings" guid="{F78A3074-8AD5-4B8B-92C4-C1C948BB7AA5}" type="UINT8" value="1"/>\n'
            '\t\t<Attribute name="ExcludeTIN" guid="{18B58CBF-AE02-4A19-8AA9-3809E8E73400}" type="UINT8" value="1"/>\n'
            '\t\t<Attribute name="ExclusionFlags" guid="{4CACC252-E6DC-419A-B20C-16EC601DF70E}" type="UINT32" value="6"/>\n'
            '\t\t<Attribute name="VegetationScale" guid="{6A043F59-E6F2-4117-A2E4-D510E7317C29}" type="UINT32" value="0"/>\n'
            '\t\t<Attribute name="VegetationDensity" guid="{41EFF715-C392-4B31-A457-50A504353A90}" type="UINT32" value="0"/>\n'
            '\t\t<Attribute name="VegetationFalloff" guid="{E82ABE17-FB4C-4F67-A28C-ED41969AEAD6}" type="FLOAT32" value="5.000000"/>\n'
            f'{v}\t</Polygon>\n')


def windsock():
    lat, lon = BORDER, PARK_E - 3 / LON  # 2012 imagery: on the border line at the parking's east edge
    return (f'\t<!-- windsock, NE corner of the US parking -->\n'
            f'\t<SceneryObject lat="{lat:.8f}" lon="{lon:.8f}" alt="0.00000000000000" pitch="0.000000" bank="0.000000" '
            'heading="0.000000" imageComplexity="VERY_SPARSE" altitudeIsAgl="TRUE" snapToGround="TRUE" snapToNormal="FALSE">\n'
            '\t\t<Windsock poleHeight="4.572000" sockLength="2.743200" lighted="FALSE" containerTitle="Windsock"/>\n'
            '\t</SceneryObject>\n')


def aprons():
    def apron(gi, heading, s, n, w, e):
        g = f' groupIndex="{gi}"' if gi else ""
        return (f'\t\t\t<Apron parentGroupID="1"{g} surface="{GRASS}" drawSurface="TRUE" drawDetail="FALSE" localUV="TRUE" '
                f'stretchUV="FALSE" flipUV="FALSE" priority="1" tiling="25.000000" heading="{heading:.6f}" falloff="0.100000" '
                'opacity="255" groundMerging="TRUE" excludeVegetationAround="TRUE" excludeVegetationInside="TRUE" isRectangle="TRUE">\n'
                + "".join(f'\t\t\t\t<Vertex lat="{la:.8f}" lon="{lo:.8f}"/>\n' for la, lo in ((s, w), (s, e), (n, e), (n, w)))
                + '\t\t\t</Apron>\n')
    return ('\t\t<Aprons>\n'
            + apron(0, 1.570796, SF, NF, WF, EF)  # mowed strip, fence to fence
            + apron(1, 1.570796, NF, POCKET_N, WF, POCKET_E)  # Canadian pocket
            + apron(2, 0.0, PARK_S, SF, WF, PARK_E)  # US parking
            + '\t\t</Aprons>\n')


def taxi():
    pts = [("Runway entry", CL, 70), ("US parking", BORDER - 12 / LAT, 70), ("Canadian pocket", CL + 15.5 / LAT, 40)]
    spots = [(BORDER - 30 / LAT, m, 0.0, 8.0) for m in (40, 60, 80, 100)] + [(CL + 18 / LAT, m, 180.0, 6.0) for m in (25, 55)]
    out = ""
    for i, (name, lat, m) in enumerate(pts):
        gi = f' groupIndex="{i}"' if i else ""
        out += (f'\t\t<TaxiwayPoint displayName="{name}" parentGroupID="2"{gi} index="{i}" type="NORMAL" orientation="FORWARD" '
                f'lat="{lat:.14f}" lon="{WF + m / LON:.14f}"/>\n')
    for k, (lat, m, hd, r) in enumerate(spots):
        gi = f' groupIndex="{k}"' if k else ""
        out += (f'\t\t<TaxiwayParking parentGroupID="4"{gi} index="{k + 3}" type="RAMP_GA_SMALL" lat="{lat:.14f}" '
                f'lon="{WF + m / LON:.14f}" heading="{hd:.6f}" radius="{r:.6f}" name="PARKING" number="{k + 1}" suffix="NONE" '
                'numberMarking="FALSE" has3DMesh="TRUE" drawDirt="FALSE" passengerAccessType="RAMP" numberBiasX="0.000000" '
                'numberBiasZ="0.000000" numberHeading="0.000000"/>\n')
    out += '\t\t<TaxiName index="0" name=""/>\n'
    tail = (f'surface="{GRASS}" centerLine="FALSE" start="%d" end="%d" width="8.000000" weightLimit="0" name="0" '
            'drawSurface="FALSE" drawDetail="FALSE" groundMerging="TRUE" excludeVegetationAround="TRUE" excludeVegetationInside="TRUE"/>\n')
    paths = [("TAXI", 0, 1), ("TAXI", 0, 2)] + [("PARKING", 1, k + 3) for k in range(4)] + [("PARKING", 2, k + 3) for k in (4, 5)]
    for i, (kind, a, b) in enumerate(paths):
        gi = f' groupIndex="{i}"' if i else ""
        out += f'\t\t<TaxiwayPath parentGroupID="3"{gi} type="{kind}" ' + tail % (a, b)
    return out


def set_attr(tag, attr, value):
    return re.sub(rf'(<{tag} [^>]*?\b{attr}=")[^"]*(")', lambda m: m.group(1) + value + m.group(2), S, count=1)


def main():
    global S
    block = "".join([f"\t{BEGIN}\n", windsock(), exclusion()] + cones() + fences() + [f"\t{END}\n"])
    S = gp.H28.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in S else "\n"
    S = S.replace("\r\n", "\n")
    if BEGIN in S:
        S = re.sub(r"\t" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _m: block, S, flags=re.S)
    else:  # first run: replace the hand-placed items before the port block
        a = S.index("\t<SceneryObject")
        b = S.index("\t<!-- BEGIN port")
        S = S[:a] + block + S[b:]
    a = S.index("\t\t<TaxiwayPoint ")
    b = S.index("\t\t<Runway ")
    S = S[:a] + taxi() + S[b:]
    S = re.sub(r"\t\t<Aprons/>\n|\t\t<Aprons>.*?</Aprons>\n", lambda _m: aprons(), S, count=1, flags=re.S)
    mid = (RW_W + RW_E) / 2
    length = (RW_E - RW_W) * LON
    S = set_attr("Runway", "lon", f"{mid:.14f}")
    S = set_attr("Runway", "length", f"{length:.6f}")
    S = set_attr("Runway", "width", "65F")
    S = set_attr("Airport", "lon", f"{mid:.14f}")
    S = re.sub(r'(<RunwayStart end="PRIMARY" [^>]*?lon=")[^"]*', lambda m: m.group(1) + f"{RW_W + 30 / LON:.14f}", S)
    S = re.sub(r'(<RunwayStart end="SECONDARY" [^>]*?lon=")[^"]*', lambda m: m.group(1) + f"{RW_E - 30 / LON:.14f}", S)
    S = re.sub(r'(<RunwayStart end="(?:PRIMARY|SECONDARY)" [^>]*?lat=")[^"]*', lambda m: m.group(1) + f"{CL:.14f}", S)
    S = set_attr("Vasi", "biasX", "12.000000")  # inside the 13.4 m fence line
    gp.H28.write_text(S.replace("\n", nl), encoding="utf-8", newline="")
    print(f"runway {length:.0f} m, centre lon {mid:.6f}; field {(EF - WF) * LON:.0f} m fence to fence; "
          f"{block.count(' cones')} cone sets, {block.count('fence, edge')} fence segments")


S = ""
if __name__ == "__main__":
    main()
