"""Generate the H28 power line (wire spans with orange marker balls) and the port pole lights, and place them in H28.xml
between BEGIN/END markers.  Run gen_port.py's palette first (it shares h28_port_palette.png), then:
    python -I airport-h28/tools/gen_powerline.py
Power line: the real line crosses the west end of the strip, N-S, about 31 ft (9.4 m) up with red/orange balls on the
span nearest the runway (FAA remark).  The wooden pole in H28.xml (library object, on the border line) is one pole; this adds
three wires from it in each direction, a library pole every SPAN m, and balls on the first span north of the pole (across the strip).
Wire height is the cross-arm guess; check it against the library pole in the sim.
Pole lights: a 7 m steel pole with a lamp head and a night-only macro light, four around each port's plaza."""
import math
import re
import sys
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_port as gp  # noqa: E402

LAT, LON = gp.LAT, gp.LON
POLE = "{4D51E533-A968-4882-A48C-0216DDC94E94}"
POLE_LAT, POLE_LON = 48.99851700, -112.78428813  # the existing pole in H28.xml
SPAN, HEIGHT, SAG = 60.0, 9.4, 1.2
ARM = 1.4  # wire offsets across the line (the T-bar), metres
BEGIN = "<!-- BEGIN power line and pole lights (generated by airport-h28/tools/gen_powerline.py) -->"
END = "<!-- END power line and pole lights -->"


def tube(m, x, pts, w=0.05):
    """Thin wire as two crossed ribbons, each double-sided."""
    for (ya, za), (yb, zb) in zip(pts, pts[1:]):
        for quad in ([(x - w, ya, za), (x + w, ya, za), (x + w, yb, zb), (x - w, yb, zb)],
                     [(x, ya - w, za), (x, ya + w, za), (x, yb + w, zb), (x, yb - w, zb)]):
            m.poly(quad, gp.DARK)
            m.poly(quad[::-1], gp.DARK)


def ball(m, cx, cy, cz, r=0.3, n=8):
    ring = lambda k: (r * math.sin(math.pi * k / n), r * math.cos(math.pi * k / n))  # noqa: E731
    for k in range(n):
        (r0, y0), (r1, y1) = ring(k), ring(k + 1)
        for i in range(n):
            a0, a1 = 2 * math.pi * i / n, 2 * math.pi * (i + 1) / n
            p = lambda rr, y, a: (cx + rr * math.cos(a), cy + y, cz + rr * math.sin(a))  # noqa: E731
            m.poly([p(r0, y0, a0), p(r1, y1, a0), p(r1, y1, a1), p(r0, y0, a1)], gp.ORANGE)
            m.poly([p(r0, y0, a1), p(r1, y1, a1), p(r1, y1, a0), p(r0, y0, a0)], gp.ORANGE)


def span(balls):
    m = gp.Mesh()
    n = 12
    for x in (-ARM, 0.0, ARM):
        pts = [(HEIGHT - 4 * SAG * (t / n) * (1 - t / n), SPAN * t / n) for t in range(n + 1)]
        tube(m, x, pts)
    if balls:
        for k, t in enumerate((0.2, 0.4, 0.6, 0.8)):
            x = (-ARM, ARM)[k % 2]
            ball(m, x, HEIGHT - 4 * SAG * t * (1 - t) - 0.3, SPAN * t)
    return m


def pole_light():
    m = gp.Mesh()
    m.box(-0.1, 0.1, 0.0, 7.0, -0.1, 0.1, gp.STEEL, top=False)
    m.box(-0.1, 0.1, 6.9, 7.0, -0.1, 1.0, gp.STEEL)  # arm
    m.box(-0.25, 0.25, 6.7, 6.9, 0.8, 1.2, gp.GREY)  # lamp head
    m.poly([(-0.2, 6.69, 1.15), (-0.2, 6.69, 0.85), (0.2, 6.69, 0.85), (0.2, 6.69, 1.15)], gp.GLOW, True)
    m.lights.append((0.0, 6.6, 1.0, 3000))
    return m


def obj(title, guid, lat, lon, hd):
    return (f"\t<!-- {title} -->\n"
            f'\t<SceneryObject lat="{lat:.8f}" lon="{lon:.8f}" alt="0.00000000000000" pitch="0.000000" bank="0.000000" '
            f'heading="{hd:.6f}" imageComplexity="VERY_SPARSE" altitudeIsAgl="TRUE" snapToGround="TRUE" snapToNormal="FALSE">\n'
            f'\t\t<LibraryObject name="{guid}" scale="1.000000"/>\n\t</SceneryObject>\n')


def main():
    ml = gp.MODELLIB
    g_ball = span(True).save(ml / "h28_wire_balls", "h28_wire_balls")
    g_plain = span(False).save(ml / "h28_wire_plain", "h28_wire_plain")
    g_light = pole_light().save(ml / "h28_pole_light", "h28_pole_light")
    out = [f"\t{BEGIN}\n"]
    dlat = SPAN / LAT
    # north: first span (with balls) crosses the strip, then plain; south: plain. Poles at each span end.
    out.append(obj("power line, span north of the pole, across the strip (marker balls)", g_ball, POLE_LAT, POLE_LON, 0))
    out.append(obj("power line, second span north", g_plain, POLE_LAT + dlat, POLE_LON, 0))
    out.append(obj("power line, span south of the pole", g_plain, POLE_LAT, POLE_LON, 180))
    out.append(obj("power line, second span south", g_plain, POLE_LAT - dlat, POLE_LON, 180))
    for k in (1, 2):
        out.append(obj(f"power line pole {k} north", POLE, POLE_LAT + k * dlat, POLE_LON, 90))
        out.append(obj(f"power line pole {k} south", POLE, POLE_LAT - k * dlat, POLE_LON, 90))
    # pole lights: four around each main building's plaza (canopy is east of the building, so the plaza is east)
    for key, title, lat, lon, w, d, h, kind, wall, roof in gp.FOOTPRINTS:
        if kind != "canopy":
            continue
        cx = lon + gp.DX + (w / 2 + 14) / LON
        for sx, sz, hd in ((-9, -(d / 2 + 5), 0), (9, -(d / 2 + 5), 0), (-9, d / 2 + 5, 180), (9, d / 2 + 5, 180)):
            out.append(obj(f"pole light, {title.split(' (')[0]}", g_light, lat + sz / LAT, cx + sx / LON, hd))
    out.append(f"\t{END}\n")
    block = "".join(out)
    s = gp.H28.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in s else "\n"
    s = s.replace("\r\n", "\n")
    if BEGIN in s:
        s = re.sub(r"\t" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _m: block, s, flags=re.S)
    else:
        i = s.index("\t<Airport displayName")
        s = s[:i] + block + s[i:]
    gp.H28.write_text(s.replace("\n", nl), encoding="utf-8", newline="")
    print(len(out) - 2, "placements")


if __name__ == "__main__":
    main()
