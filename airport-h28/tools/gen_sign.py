"""Adds the "Welcome to Alberta, Wild Rose Country" sign on the east shoulder of AB-62, north of the CBSA port.

    python -I airport-h28/tools/gen_sign.py

Writes one textured model (h28_sign_alberta, with its own 2048 x 2048 texture h28_sign_alberta.png in
modelLib/texture) and a placement between its own BEGIN/END markers in H28.xml, so gen_port.py does not touch it.
It uses gen_port.Mesh for the glTF but not the shared palette, so it can run in any order with the other generators.
Needs Pillow and Arial Bold (C:/Windows/Fonts/arialbd.ttf) for the lettering.

Reference: docs/h28/reference/fbgroup-02-alberta-welcome-sign.jpg (front-on, 2048 x 1536) and
travelingwards-e-entering-alberta.jpg. Every size below is measured off the first photo at 0.004189 m per pixel,
assuming the board is 16 ft (4.88 m) wide; photo pixel x 982.5 is the board centre and y 1300 is the ground.
- Board: dark brown wood with a lighter frame and a recessed rough-sawn panel, white lettering (Arial Bold, each line
  stretched to the box it fills in the photo) and the wild rose decal (pink flower, bud, teal leaves, black outline,
  white sticker edge) at the right of "ALBERTA". The back is plain wood.
- Posts: two tall 12 x 12 in posts either side of the board, shorter outer posts (left 3.4 m, right 2.9 m), and legs
  under the board's ends. Gravel bed with timber edging, and a cream concrete planter in front of the right posts.

Position: Esri World Imagery (docs/h28/fetch_esri.py, alberta-sign.png) shows the sign's gravel pad, about 7.6 x 4.5 m
and square to the road, 22 m east of the road centre at the north edge of the house yard north of the CBSA sheds.
The Esri road centre is about 7 m east of OSM's (-112.7884, which the sim aerial matches), so the offset is taken from
the road. The sign faces south, to northbound traffic coming from Montana.
"""

import json
import math
import random
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_port as gp  # noqa: E402

H28 = gp.H28
BEGIN = "<!-- BEGIN Welcome to Alberta sign (generated by airport-h28/tools/gen_sign.py) -->"
END = "<!-- END Welcome to Alberta sign -->"
NAME = "h28_sign_alberta"
FONT = Path("C:/Windows/Fonts/arialbd.ttf")

ROAD_LON = -112.7884  # road centre (OSM and the sim aerial)
LAT, LON = 49.00066, ROAD_LON + 22.4 / gp.LON  # board centre: Esri pad centre plus 0.8 m north
HEADING = 0.0  # model +Z is north; the lettering is on the south face

# photo -> model metres
K = 4.88 / 1165  # board is 1165 px wide in the photo
PX0, PY0 = 982.5, 1300.0
BOARD = (400, 1565, 370, 960)  # photo px: left, right, top, bottom


def mx(px):
    return (px - PX0) * K


def my(py):
    return (PY0 - py) * K


# texture atlas (pixels in a 2048 x 2048 image): x, y, w, h
A = 2048
FRONT = (0, 0, 2048, 1024)
BACK = (0, 1024, 1024, 512)
POST = (1024, 1024, 512, 512)
GRAVEL = (1536, 1024, 512, 512)
CONCRETE = (0, 1536, 512, 512)
SOIL = (512, 1536, 512, 512)
EDGING = (1024, 1536, 512, 512)
ENDGRAIN = (1536, 1536, 512, 512)
INSET = 6  # keeps mipmaps from bleeding across regions

WHITE = (238, 238, 232)
FRAME = (66, 45, 33)
PANEL = (50, 37, 30)
POSTC = (44, 33, 26)


# ---------------------------------------------------------------- texture

def wood(w, h, base, rnd, vertical=False, streaks=900, spread=14):
    """Rough-sawn wood: a base colour with many thin streaks along the grain."""
    if vertical:
        return wood(h, w, base, rnd, False, streaks, spread).transpose(Image.Transpose.ROTATE_90)
    im = Image.new("RGB", (w, h), base)
    d = ImageDraw.Draw(im)
    for _ in range(streaks):
        y = rnd.uniform(0, h)
        x0 = rnd.uniform(-w * 0.2, w)
        ln = rnd.uniform(w * 0.1, w * 0.8)
        k = rnd.uniform(-spread, spread)
        c = tuple(max(0, min(255, int(v + k + rnd.uniform(-3, 3)))) for v in base)
        d.line([(x0, y), (x0 + ln, y + rnd.uniform(-1.5, 1.5))], fill=c, width=rnd.choice((1, 1, 2, 3)))
    return im.filter(ImageFilter.GaussianBlur(0.7))


def speckle(im, rnd, n, colour, size=(1, 4)):
    d = ImageDraw.Draw(im)
    for _ in range(n):
        x, y = rnd.uniform(0, im.width), rnd.uniform(0, im.height)
        r = rnd.uniform(*size)
        d.ellipse([x - r, y - r * 0.5, x + r, y + r * 0.5], fill=colour)


def rose_layer(size, T, s):
    """The wild rose decal as RGBA. T maps photo pixels to layer pixels, s is layer pixels per photo pixel."""
    shapes = Image.new("L", size, 0)
    fill = Image.new("RGBA", size, (0, 0, 0, 0))
    ds, df = ImageDraw.Draw(shapes), ImageDraw.Draw(fill)

    def ell(cx, cy, rx, ry, colour, ang=0.0, n=40):
        pts = []
        for k in range(n):
            a = 2 * math.pi * k / n
            x, y = rx * math.cos(a), ry * math.sin(a)
            ca, sa = math.cos(math.radians(ang)), math.sin(math.radians(ang))
            pts.append(T(cx + x * ca - y * sa, cy + x * sa + y * ca))
        ds.polygon(pts, fill=255)
        df.polygon(pts, fill=colour)
        return pts

    leaf, leaf_dark = (104, 170, 140), (60, 120, 96)
    pink, pink_dark = (234, 148, 160), (196, 98, 116)
    # stem from the lower-left leaf up to the flower and the bud
    for a, b in (((1292, 745), (1360, 690)), ((1338, 640), (1352, 690)), ((1360, 690), (1400, 700))):
        ds.line([T(*a), T(*b)], fill=255, width=int(9 * s))
        df.line([T(*a), T(*b)], fill=leaf_dark + (255,), width=int(9 * s))
    # leaves
    for cx, cy, rx, ry, ang in ((1318, 700, 15, 26, -25), (1303, 735, 12, 20, 50), (1447, 727, 14, 20, 30),
                                (1472, 590, 8, 18, 30), (1372, 718, 11, 16, -60)):
        ell(cx, cy, rx, ry, leaf + (255,), ang)
    # bud and its sepals
    ell(1336, 604, 13, 22, pink + (255,), 15)
    ell(1340, 628, 11, 9, leaf + (255,), 0)
    # flower: five petals round a yellow centre
    cx, cy = 1424, 655
    for k in range(5):
        a = math.radians(-90 + 72 * k + 10)
        ell(cx + 33 * math.cos(a), cy + 33 * math.sin(a), 38, 34, pink + (255,), math.degrees(a))
    ell(cx, cy, 40, 38, pink + (255,))
    # petal creases
    for k in range(5):
        a = math.radians(-90 + 72 * k + 46)
        df.line([T(cx + 22 * math.cos(a), cy + 22 * math.sin(a)), T(cx + 62 * math.cos(a), cy + 62 * math.sin(a))],
                fill=pink_dark + (255,), width=max(2, int(3 * s)))
    df.line([T(1330, 590), T(1336, 622)], fill=pink_dark + (255,), width=max(2, int(3 * s)))
    # leaf veins
    for a, b in (((1305, 715), (1330, 685)), ((1440, 740), (1455, 715)), ((1295, 745), (1310, 725))):
        df.line([T(*a), T(*b)], fill=leaf_dark + (255,), width=max(2, int(2 * s)))
    # centre and stamens
    ell(cx, cy, 13, 13, (236, 214, 70, 255))
    for k in range(12):
        a = 2 * math.pi * k / 12
        x, y = T(cx + 17 * math.cos(a), cy + 17 * math.sin(a))
        r = 2.2 * s
        df.ellipse([x - r, y - r, x + r, y + r], fill=(200, 140, 40, 255))

    # sticker: white edge, black outline, then the colours
    def grow(px):
        n = int(px * s) | 1
        return shapes.filter(ImageFilter.MaxFilter(n if n >= 3 else 3))

    out = Image.new("RGBA", size, (0, 0, 0, 0))
    out.paste((236, 236, 230, 255), mask=grow(13))
    out.paste((22, 22, 22, 255), mask=grow(7))
    out.alpha_composite(fill)
    return out


def lettering(img, text, box, ss):
    """Paint `text` in white, stretched to fill box = (x0, y0, x1, y1) in texture pixels, with a small shadow."""
    font = ImageFont.truetype(str(FONT), 400)
    probe = Image.new("L", (int(font.getlength(text)) + 100, 600), 0)
    ImageDraw.Draw(probe).text((50, 50), text, font=font, fill=255)
    probe = probe.crop(probe.getbbox())
    x0, y0, x1, y1 = (int(round(v)) for v in box)
    mask = probe.resize((x1 - x0, y1 - y0), Image.Resampling.LANCZOS)
    shadow = Image.new("RGB", mask.size, (18, 12, 10))
    img.paste(shadow, (x0 + int(3 * ss), y0 + int(4 * ss)), mask.point(lambda v: v * 6 // 10))
    img.paste(Image.new("RGB", mask.size, WHITE), (x0, y0), mask)


def board_face(w, h, rnd, ss, front):
    """Board face, w x h texture pixels (drawn at ss times size, then reduced)."""
    W, H = w * ss, h * ss
    sx, sy = W / (BOARD[1] - BOARD[0]), H / (BOARD[3] - BOARD[2])
    T = lambda px, py: ((px - BOARD[0]) * sx, (py - BOARD[2]) * sy)  # noqa: E731
    img = wood(W, H, FRAME, rnd, streaks=int(500 * ss), spread=10)
    # recessed rough-sawn panel with a routed edge (photo: inner panel 432..1530 x 405..925, corner radius ~30 px)
    panel = wood(W, H, PANEL, rnd, streaks=int(2600 * ss), spread=16)
    mask = Image.new("L", (W, H), 0)
    p0, p1 = T(432, 405), T(1532, 926)
    ImageDraw.Draw(mask).rounded_rectangle([p0, p1], radius=int(30 * sx), fill=255)
    groove = Image.new("L", (W, H), 0)
    ImageDraw.Draw(groove).rounded_rectangle([p0, p1], radius=int(30 * sx), outline=255, width=int(5 * sx))
    img.paste(panel, (0, 0), mask)
    img.paste((26, 19, 15), (0, 0), groove)
    hi = Image.new("L", (W, H), 0)  # lit lower lip of the recess
    ImageDraw.Draw(hi).rounded_rectangle([(p0[0], p0[1] + 4 * sx), (p1[0], p1[1] + 4 * sx)], radius=int(30 * sx),
                                         outline=255, width=int(2 * sx))
    img.paste((92, 66, 48), (0, 0), hi)
    # paint worn off the frame: lighter brown flecks along the edges
    fl = Image.new("RGB", (W, H))
    fm = Image.new("L", (W, H), 0)
    speckle(fm, rnd, int(260 * ss), 255, (1 * ss, 4 * ss))
    edge = Image.new("L", (W, H), 255)
    ImageDraw.Draw(edge).rectangle([T(415, 385), T(1550, 945)], fill=0)
    fm = Image.composite(fm, Image.new("L", (W, H), 0), edge)
    fl.paste((118, 82, 58), (0, 0, W, H))
    img.paste(fl, (0, 0), fm)
    if front:
        lettering(img, "WELCOME TO", (*T(562, 489), *T(1162, 561)), ss)
        lettering(img, "ALBERTA", (*T(534, 598), *T(1284, 734)), ss)
        lettering(img, "WILD ROSE COUNTRY", (*T(558, 767), *T(1254, 824)), ss)
        img.paste(rose := rose_layer((W, H), T, sx), (0, 0), rose)
    return img.resize((w, h), Image.Resampling.LANCZOS)


def gravel(w, h, rnd):
    im = Image.new("RGB", (w, h), (150, 144, 134))
    d = ImageDraw.Draw(im)
    for _ in range(9000):
        x, y, r = rnd.uniform(0, w), rnd.uniform(0, h), rnd.uniform(0.8, 2.6)
        g = rnd.randint(95, 215)
        d.ellipse([x - r, y - r, x + r, y + r], fill=(g, g - rnd.randint(0, 12), g - rnd.randint(4, 22)))
    return im.filter(ImageFilter.GaussianBlur(0.4))


def concrete(w, h, rnd):
    im = Image.new("RGB", (w, h), (206, 200, 182))
    speckle(im, rnd, 2500, (176, 170, 152), (0.5, 1.5))
    speckle(im, rnd, 800, (222, 218, 204), (0.5, 1.5))
    return im.filter(ImageFilter.GaussianBlur(0.8))


def soil(w, h, rnd):
    im = Image.new("RGB", (w, h), (78, 62, 46))
    speckle(im, rnd, 3000, (60, 48, 36), (1, 3))
    speckle(im, rnd, 400, (96, 112, 60), (1, 4))  # a few weeds
    return im.filter(ImageFilter.GaussianBlur(0.6))


def end_grain(w, h, rnd):
    im = Image.new("RGB", (w, h), (98, 86, 76))  # weathered grey-brown post tops (photo)
    d = ImageDraw.Draw(im)
    for k in range(18):
        r = w * 0.04 * (k + 1)
        d.ellipse([w / 2 - r, h / 2 - r, w / 2 + r, h / 2 + r], outline=(82, 70, 62), width=2)
    d.line([(w * 0.5, h * 0.5), (w * 0.9, h * 0.3)], fill=(40, 30, 26), width=4)  # check crack
    return im.filter(ImageFilter.GaussianBlur(1.0))


def write_texture(path):
    rnd = random.Random(28)
    im = Image.new("RGB", (A, A), (0, 0, 0))
    paste = lambda region, tile: im.paste(tile, region[:2])  # noqa: E731
    paste(FRONT, board_face(FRONT[2], FRONT[3], rnd, 2, True))
    paste(BACK, board_face(BACK[2], BACK[3], rnd, 2, False))
    post = wood(POST[2], POST[3], POSTC, rnd, vertical=True, streaks=1400, spread=12)
    speckle(post, rnd, 40, (20, 16, 14), (2, 4))  # bolt heads and knots
    paste(POST, post)
    paste(GRAVEL, gravel(GRAVEL[2], GRAVEL[3], rnd))
    paste(CONCRETE, concrete(CONCRETE[2], CONCRETE[3], rnd))
    paste(SOIL, soil(SOIL[2], SOIL[3], rnd))
    paste(EDGING, wood(EDGING[2], EDGING[3], (112, 106, 94), rnd, streaks=900, spread=18))
    paste(ENDGRAIN, end_grain(ENDGRAIN[2], ENDGRAIN[3], rnd))
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, optimize=True)
    path.with_name(path.name + ".xml").write_text(
        '<BitmapConfiguration>\n\t<BitmapSlot>MTL_BITMAP_DECAL0</BitmapSlot>\n</BitmapConfiguration>\n')


# ---------------------------------------------------------------- geometry

def dot(a, b):
    return sum(a[i] * b[i] for i in range(3))


def quad(m, pts, out, region, right, up):
    """Polygon facing `out`, its texture stretched over `region`: u along `right`, v down along `up`."""
    n0 = len(m.pos)
    m.poly_out(pts, 0, out)
    s = [dot(p, right) for p in pts]
    t = [dot(p, up) for p in pts]
    s0, s1, t0, t1 = min(s), max(s), min(t), max(t)
    rx, ry, rw, rh = region
    for k in range(n0, len(m.pos)):
        p = m.pos[k]
        u = (rx + INSET + (dot(p, right) - s0) / ((s1 - s0) or 1) * (rw - 2 * INSET)) / A
        v = (ry + INSET + (t1 - dot(p, up)) / ((t1 - t0) or 1) * (rh - 2 * INSET)) / A
        m.uv[k] = (u, v)


def tbox(m, x0, x1, y0, y1, z0, z1, side, top=None, south=None, north=None, faces="nsewt"):
    """Box with each face's texture stretched over a region; `south`/`north` override the side region."""
    P = lambda x, y, z: (x, y, z)  # noqa: E731
    if "s" in faces:
        quad(m, [P(x0, y0, z0), P(x1, y0, z0), P(x1, y1, z0), P(x0, y1, z0)], (0, 0, -1), south or side, (1, 0, 0), (0, 1, 0))
    if "n" in faces:
        quad(m, [P(x0, y0, z1), P(x1, y0, z1), P(x1, y1, z1), P(x0, y1, z1)], (0, 0, 1), north or side, (-1, 0, 0), (0, 1, 0))
    if "e" in faces:
        quad(m, [P(x1, y0, z0), P(x1, y0, z1), P(x1, y1, z1), P(x1, y1, z0)], (1, 0, 0), side, (0, 0, 1), (0, 1, 0))
    if "w" in faces:
        quad(m, [P(x0, y0, z0), P(x0, y0, z1), P(x0, y1, z1), P(x0, y1, z0)], (-1, 0, 0), side, (0, 0, -1), (0, 1, 0))
    if "t" in faces:
        quad(m, [P(x0, y1, z0), P(x1, y1, z0), P(x1, y1, z1), P(x0, y1, z1)], (0, 1, 0), top or side, (1, 0, 0), (0, 0, 1))


def build_sign():
    m = gp.Mesh()
    sink = -0.3  # posts run into the ground to cover slopes
    hd = 0.15  # half the depth of a 12 x 12 in post
    # board, 0.15 m thick, between the tall posts
    bx0, bx1, by0, by1 = mx(BOARD[0]), mx(BOARD[1]), my(BOARD[3]), my(BOARD[2])
    tbox(m, bx0, bx1, by0, by1, -0.075, 0.075, POST, south=FRONT, north=BACK, faces="snt")
    quad(m, [(bx0, by0, -0.075), (bx1, by0, -0.075), (bx1, by0, 0.075), (bx0, by0, 0.075)], (0, -1, 0), POST,
         (1, 0, 0), (0, 0, 1))  # underside, seen from the ground
    # tall posts (tops: left photo y 258, right 265) and the shorter outer posts, set 0.1 m back
    for px0, px1, top, z in ((320, 400, 258, 0.0), (1565, 1645, 265, 0.0), (245, 318, 478, 0.12), (1650, 1708, 610, 0.12)):
        tbox(m, mx(px0), mx(px1), sink, my(top), z - hd, z + hd, POST, top=ENDGRAIN)
    # legs under the board's ends
    for px0, px1 in ((400, 472), (1483, 1565)):
        tbox(m, mx(px0), mx(px1), sink, by0, -hd, hd, POST, faces="nsew")
    # gravel bed with timber edging (Esri pad about 7.6 x 4.5 m; the sign stands 0.8 m north of its centre)
    gx0, gx1, gz0, gz1 = -3.8, 3.8, -3.05, 1.45
    tbox(m, gx0, gx1, -0.15, 0.04, gz0, gz1, GRAVEL)
    e = 0.1
    for x0, x1, z0, z1 in ((gx0 - e, gx1 + e, gz0 - e, gz0), (gx0 - e, gx1 + e, gz1, gz1 + e),
                           (gx0 - e, gx0, gz0, gz1), (gx1, gx1 + e, gz0, gz1)):
        tbox(m, x0, x1, -0.15, 0.1, z0, z1, EDGING)
    # concrete planter in front of the right posts (photo x 1535..1915), 0.7 m tall, with soil
    px0, px1, pz0, pz1, ph, w = 2.33, 3.92, -1.65, -0.85, 0.7, 0.1
    tbox(m, px0, px1, -0.1, ph, pz0, pz1, CONCRETE, faces="nsew")
    for x0, x1, z0, z1 in ((px0, px1, pz0, pz0 + w), (px0, px1, pz1 - w, pz1), (px0, px0 + w, pz0 + w, pz1 - w),
                           (px1 - w, px1, pz0 + w, pz1 - w)):
        tbox(m, x0, x1, -0.1, ph, z0, z1, CONCRETE, faces="t")
    tbox(m, px0 + w, px1 - w, -0.1, ph - 0.1, pz0 + w, pz1 - w, CONCRETE, top=SOIL, faces="t")
    x0, x1, z0, z1, y0, y1 = px0 + w, px1 - w, pz0 + w, pz1 - w, ph - 0.1, ph  # inner walls above the soil, facing in
    P = lambda x, y, z: (x, y, z)  # noqa: E731
    quad(m, [P(x0, y0, z0), P(x1, y0, z0), P(x1, y1, z0), P(x0, y1, z0)], (0, 0, 1), CONCRETE, (1, 0, 0), (0, 1, 0))
    quad(m, [P(x0, y0, z1), P(x1, y0, z1), P(x1, y1, z1), P(x0, y1, z1)], (0, 0, -1), CONCRETE, (1, 0, 0), (0, 1, 0))
    quad(m, [P(x0, y0, z0), P(x0, y0, z1), P(x0, y1, z1), P(x0, y1, z0)], (1, 0, 0), CONCRETE, (0, 0, 1), (0, 1, 0))
    quad(m, [P(x1, y0, z0), P(x1, y0, z1), P(x1, y1, z1), P(x1, y1, z0)], (-1, 0, 0), CONCRETE, (0, 0, 1), (0, 1, 0))
    return m


def save(m):
    folder = gp.MODELLIB / NAME
    guid = m.save(folder, NAME)
    gltf = folder / f"{NAME}.gltf"
    g = json.loads(gltf.read_text())
    g["asset"]["generator"] = "airport-h28/tools/gen_sign.py"
    g["images"] = [{"uri": f"{NAME}.png"}]
    g["samplers"] = [{"magFilter": 9729, "minFilter": 9987, "wrapS": 33071, "wrapT": 33071}]  # linear, mipmapped
    for mat in g["materials"]:
        mat["name"] = "h28_sign"
        mat["pbrMetallicRoughness"]["roughnessFactor"] = 0.85
    gltf.write_text(json.dumps(g, indent=1))
    return guid


def main():
    write_texture(gp.MODELLIB / "texture" / f"{NAME}.png")
    guid = save(build_sign())
    block = "".join([
        f"\t{BEGIN}\n",
        "\t<!-- Welcome to Alberta sign, east shoulder of AB-62 north of the CBSA port, facing south (Esri imagery) -->\n",
        f'\t<SceneryObject lat="{LAT:.8f}" lon="{LON:.8f}" alt="0.00000000000000" pitch="0.000000" bank="0.000000" '
        f'heading="{HEADING:.6f}" imageComplexity="VERY_SPARSE" altitudeIsAgl="TRUE" snapToGround="TRUE" snapToNormal="FALSE">\n'
        f'\t\t<LibraryObject name="{guid}" scale="1.000000"/>\n\t</SceneryObject>\n',
        f"\t{END}\n",
    ])
    s = H28.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in s else "\n"
    s = s.replace("\r\n", "\n")
    if BEGIN in s:
        s = re.sub(r"\t" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _m: block, s, flags=re.S)
    else:
        i = s.index("\t<Airport displayName")
        s = s[:i] + block + s[i:]
    H28.write_text(s.replace("\n", nl), encoding="utf-8", newline="")
    print("wrote", NAME, guid, f"at {LAT:.6f}, {LON:.6f}")


if __name__ == "__main__":
    main()
