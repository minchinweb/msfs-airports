"""Generate CYXD historic building models (glTF ModelLib) and their placement XML.

Reads  docs/cyxd/historic-buildings-genericbuilding.xml  (old GenericBuilding placements; source of truth
for position/heading/size), writes
  airport-cyxd/PackageSources/modelLib/<name>/<name>.{gltf,bin,xml}
  airport-cyxd/PackageSources/modelLib/texture/cyxd_palette.png(.xml)
and replaces the block between the BEGIN/END markers in CYXD.xml with LibraryObject placements.

Run:  python -I airport-cyxd/tools/gen_buildings.py   (from the repo root)

Model frame: origin on the ground at the footprint centre, Y up, +Z = object heading direction.
Hotels (Edmonton Inn, Chateau Louis) are skipped on purpose.
"""
import json, math, re, struct, uuid, zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs/cyxd/historic-buildings-genericbuilding.xml"
CYXD = ROOT / "airport-cyxd/PackageSources/Scenery/airport-cyxd/CYXD.xml"
MODELLIB = ROOT / "airport-cyxd/PackageSources/modelLib"
NS = uuid.UUID("5d0c6c7e-0c1d-4a53-9b6e-0c7d00000001")
BEGIN = "<!-- BEGIN historic buildings (generated by airport-cyxd/tools/gen_buildings.py) -->"
END = "<!-- END historic buildings -->"

# palette swatches (u index) -----------------------------------------------------------------
WALL, ROOF, METAL, DARK, BRICK, TRIM, RED, WHITE = range(8)
PALETTE = [(178, 172, 160), (70, 66, 64), (122, 130, 130), (38, 40, 46), (150, 88, 72), (204, 200, 190), (196, 52, 40), (236, 234, 230)]
SW = 16


def write_palette(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    w, h = SW * len(PALETTE), SW
    raw = b"".join(b"\x00" + b"".join(bytes(PALETTE[x // SW]) for x in range(w)) for _ in range(h))

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) \
        + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.write_bytes(png)
    path.with_name(path.name + ".xml").write_text(
        '<BitmapConfiguration>\n\t<BitmapSlot>MTL_BITMAP_DECAL0</BitmapSlot>\n</BitmapConfiguration>\n')


# mesh builder ------------------------------------------------------------------------------
class Mesh:
    def __init__(self):
        self.pos, self.nrm, self.uv, self.idx = [], [], [], []

    def poly(self, pts, sw, centre):
        """Planar convex polygon, wound/flipped so the normal points away from `centre`."""
        a, b, c = pts[0], pts[1], pts[2]
        u = [b[i] - a[i] for i in range(3)]
        v = [c[i] - a[i] for i in range(3)]
        n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]]
        cen = [sum(p[i] for p in pts) / len(pts) for i in range(3)]
        if sum(n[i] * (cen[i] - centre[i]) for i in range(3)) < 0:
            pts = pts[::-1]
            n = [-x for x in n]
        ln = math.sqrt(sum(x * x for x in n)) or 1.0
        n = [x / ln for x in n]
        base = len(self.pos)
        uvp = ((sw + 0.5) / len(PALETTE), 0.5)
        for p in pts:
            self.pos.append(p)
            self.nrm.append(n)
            self.uv.append(uvp)
        for i in range(1, len(pts) - 1):
            self.idx += [base, base + i, base + i + 1]

    def box(self, x0, x1, y0, y1, z0, z1, sw, top=True):
        c = ((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2)
        P = lambda x, y, z: (x, y, z)
        self.poly([P(x0, y0, z0), P(x1, y0, z0), P(x1, y1, z0), P(x0, y1, z0)], sw, c)
        self.poly([P(x0, y0, z1), P(x1, y0, z1), P(x1, y1, z1), P(x0, y1, z1)], sw, c)
        self.poly([P(x0, y0, z0), P(x0, y0, z1), P(x0, y1, z1), P(x0, y1, z0)], sw, c)
        self.poly([P(x1, y0, z0), P(x1, y0, z1), P(x1, y1, z1), P(x1, y1, z0)], sw, c)
        if top:
            self.poly([P(x0, y1, z0), P(x1, y1, z0), P(x1, y1, z1), P(x0, y1, z1)], sw, c)

    def gable(self, x0, x1, y0, ridge_h, z0, z1, along_z, sw_roof, sw_wall):
        """Gable roof on top of a box top at y0; ridge parallel to Z if along_z else X."""
        P = lambda x, y, z: (x, y, z)
        yr = y0 + ridge_h
        if along_z:
            xm = (x0 + x1) / 2
            c = (xm, y0, (z0 + z1) / 2)
            self.poly([P(x0, y0, z0), P(xm, yr, z0), P(xm, yr, z1), P(x0, y0, z1)], sw_roof, (xm, y0 - 5, c[2]))
            self.poly([P(x1, y0, z0), P(x1, y0, z1), P(xm, yr, z1), P(xm, yr, z0)], sw_roof, (xm, y0 - 5, c[2]))
            self.poly([P(x0, y0, z0), P(x1, y0, z0), P(xm, yr, z0)], sw_wall, (xm, y0 - 1, c[2]))
            self.poly([P(x0, y0, z1), P(x1, y0, z1), P(xm, yr, z1)], sw_wall, (xm, y0 - 1, c[2]))
        else:
            zm = (z0 + z1) / 2
            c = ((x0 + x1) / 2, y0, zm)
            self.poly([P(x0, y0, z0), P(x0, yr, zm), P(x1, yr, zm), P(x1, y0, z0)], sw_roof, (c[0], y0 - 5, zm))
            self.poly([P(x0, y0, z1), P(x1, y0, z1), P(x1, yr, zm), P(x0, yr, zm)], sw_roof, (c[0], y0 - 5, zm))
            self.poly([P(x0, y0, z0), P(x0, y0, z1), P(x0, yr, zm)], sw_wall, (c[0] + 1, y0 - 1, zm))
            self.poly([P(x1, y0, z0), P(x1, y0, z1), P(x1, yr, zm)], sw_wall, (c[0] - 1, y0 - 1, zm))

    def window(self, face, origin, u_axis, w, h, off=0.06):
        """Dark window quad lying on a wall: origin = lower-left corner on the wall, face = outward normal."""
        o = [origin[i] + face[i] * off for i in range(3)]
        up = (0, 1, 0)
        p = [tuple(o[i] for i in range(3)),
             tuple(o[i] + u_axis[i] * w for i in range(3)),
             tuple(o[i] + u_axis[i] * w + up[i] * h for i in range(3)),
             tuple(o[i] + up[i] * h for i in range(3))]
        centre = tuple(p[0][i] - face[i] for i in range(3))
        self.poly(p, DARK, centre)

    def save(self, folder, name):
        folder.mkdir(parents=True, exist_ok=True)
        n = len(self.pos)
        assert n < 65535
        pos = b"".join(struct.pack("<3f", *p) for p in self.pos)
        nrm = b"".join(struct.pack("<3f", *p) for p in self.nrm)
        uv = b"".join(struct.pack("<2f", *p) for p in self.uv)
        idx = b"".join(struct.pack("<H", i) for i in self.idx)
        if len(idx) % 4:
            idx += b"\x00\x00"
        blob = pos + nrm + uv + idx
        (folder / f"{name}.bin").write_bytes(blob)
        mn = [min(p[i] for p in self.pos) for i in range(3)]
        mx = [max(p[i] for p in self.pos) for i in range(3)]
        g = {
            "asset": {"version": "2.0", "generator": "airport-cyxd/tools/gen_buildings.py",
                      "extensions": {"ASOBO_normal_map_convention": {"tangent_space_convention": "DirectX"}}},
            "extensionsUsed": ["ASOBO_normal_map_convention"],
            "scene": 0, "scenes": [{"nodes": [0]}],
            "nodes": [{"mesh": 0, "name": name}],
            "meshes": [{"name": name, "primitives": [{
                "attributes": {"POSITION": 0, "NORMAL": 1, "TEXCOORD_0": 2}, "indices": 3, "mode": 4, "material": 0}]}],
            "materials": [{"name": "cyxd_palette", "pbrMetallicRoughness": {
                "baseColorTexture": {"index": 0}, "metallicFactor": 0.0, "roughnessFactor": 0.9}}],
            "textures": [{"sampler": 0, "source": 0}],
            "samplers": [{"magFilter": 9728, "minFilter": 9728}],
            "images": [{"uri": "cyxd_palette.png"}],
            "accessors": [
                {"bufferView": 0, "componentType": 5126, "count": n, "type": "VEC3", "min": mn, "max": mx},
                {"bufferView": 1, "componentType": 5126, "count": n, "type": "VEC3"},
                {"bufferView": 2, "componentType": 5126, "count": n, "type": "VEC2"},
                {"bufferView": 3, "componentType": 5123, "count": len(self.idx), "type": "SCALAR"}],
            "bufferViews": [
                {"buffer": 0, "byteOffset": 0, "byteLength": len(pos)},
                {"buffer": 0, "byteOffset": len(pos), "byteLength": len(nrm)},
                {"buffer": 0, "byteOffset": len(pos) + len(nrm), "byteLength": len(uv)},
                {"buffer": 0, "byteOffset": len(pos) + len(nrm) + len(uv), "byteLength": len(self.idx) * 2}],
            "buffers": [{"uri": f"{name}.bin", "byteLength": len(blob)}],
        }
        (folder / f"{name}.gltf").write_text(json.dumps(g, indent=1))
        guid = "{" + str(uuid.uuid5(NS, name)).upper() + "}"
        (folder / f"{name}.xml").write_text(
            f'<?xml version="1.0" encoding="utf-8"?>\n<ModelInfo guid="{guid}" version="1.1">\n'
            f'\t<LODS>\n\t\t<LOD minSize="0" ModelFile="{name}.gltf"/>\n\t</LODS>\n</ModelInfo>\n')
        return guid


# models ------------------------------------------------------------------------------------
def simple_building(roof, sx, sz, h, rh):
    m = Mesh()
    m.box(-sx / 2, sx / 2, 0, h, -sz / 2, sz / 2, WALL, top=(roof != "RIDGE"))
    if roof == "RIDGE":
        # ridge along the longer horizontal axis
        m.gable(-sx / 2, sx / 2, h, rh, -sz / 2, sz / 2, along_z=(sz >= sx), sw_roof=ROOF, sw_wall=WALL)
    return m


def window_row(m, x0, x1, y, z, count, w, h, face, axis):
    """Row of `count` windows across a wall between x0..x1 (along `axis`), at height y, on plane z."""
    span = x1 - x0
    gap = (span - count * w) / (count + 1)
    for i in range(count):
        s = x0 + gap + i * (w + gap)
        if axis == "x":
            m.window(face, (s, y, z), (1, 0, 0), w, h)
        else:  # along z: wall plane is x=z param
            m.window(face, (z, y, s), (0, 0, 1), w, h)


def tower(m, cx, cz, sx, sz, h, floors, front=(0, 0, 1)):
    x0, x1, z0, z1 = cx - sx / 2, cx + sx / 2, cz - sz / 2, cz + sz / 2
    m.box(x0, x1, 0, h, z0, z1, WALL)
    m.box(x0 - 0.4, x1 + 0.4, h, h + 1.0, z0 - 0.4, z1 + 0.4, TRIM)  # parapet cap
    fh = h / floors
    for f in range(floors):
        y = f * fh + fh * 0.35
        if f == 0:
            continue
        window_row(m, x0, x1, y, z1, 2, 1.2, 1.8, (0, 0, 1), "x")
        window_row(m, x0, x1, y, z0, 2, 1.2, 1.8, (0, 0, -1), "x")
        window_row(m, z0, z1, y, x1, 2, 1.2, 1.8, (1, 0, 0), "z")
        window_row(m, z0, z1, y, x0, 2, 1.2, 1.8, (-1, 0, 0), "z")


def hangar_1938():
    """1938 arched hangar + main tower + small tower + office wing (EA-160-398/402/466/1331/1332, 1944 aerial).

    Local frame: +Z = front (doors / landmark face, heading direction), +X = right of the front as seen from the front.
    Hangar centred at the origin; tower and wing sit to its right along the front, small tower to its left.
    """
    m = Mesh()
    span, length, wall, rise = 42.0, 44.0, 7.0, 6.0
    xh0, xh1, zf, zb = -span / 2, span / 2, length / 2, -length / 2
    # walls
    m.box(xh0, xh1, 0, wall, zb, zf, METAL, top=False)
    # barrel vault
    n = 14
    prof = []
    for i in range(n + 1):
        a = math.pi * i / n
        prof.append((math.cos(a) * span / 2, wall + math.sin(a) * rise))
    prof = prof[::-1]  # left to right
    cen = (0, wall, 0)
    for i in range(n):
        (xa, ya), (xb, yb) = prof[i], prof[i + 1]
        m.poly([(xa, ya, zb), (xb, yb, zb), (xb, yb, zf), (xa, ya, zf)], METAL, (0, wall - 3, 0))
    # end arches (front and back)
    for z, sw in ((zf, METAL), (zb, METAL)):
        m.poly([(xh0, wall, z)] + [(x, y, z) for x, y in prof] + [(xh1, wall, z)], sw, (0, wall, 0))
    # big front doors (open, dark) and side windows
    m.poly([(-16, 0.0, zf + 0.08), (16, 0.0, zf + 0.08), (16, 7.0, zf + 0.08), (-16, 7.0, zf + 0.08)], DARK, (0, 3, 0))
    m.poly([(-16, 7.0, zf + 0.08), (16, 7.0, zf + 0.08), (11, 11.0, zf + 0.08), (-11, 11.0, zf + 0.08)], DARK, (0, 5, 0))
    for sgn in (-1, 1):
        for i in range(6):
            z = zb + 4 + i * 6.5
            m.window((sgn, 0, 0), (sgn * (span / 2), 3.2, z), (0, 0, 1), 3.0, 1.6)
    # main tower, flush with front face, right of hangar
    tw, td, th = 11.0, 11.0, 22.0
    tcx, tcz = xh1 + tw / 2, zf - td / 2
    tower(m, tcx, tcz, tw, td, th, 5)
    # office wing continues to the right, two storeys, hip-ish gable roof along X
    ww, wd, wh = 30.0, 13.0, 8.0
    wcx, wcz = tcx + tw / 2 + ww / 2, zf - wd / 2 - 1.0
    m.box(wcx - ww / 2, wcx + ww / 2, 0, wh, wcz - wd / 2, wcz + wd / 2, WALL, top=False)
    m.gable(wcx - ww / 2, wcx + ww / 2, wh, 3.5, wcz - wd / 2, wcz + wd / 2, along_z=False, sw_roof=ROOF, sw_wall=WALL)
    for y in (1.2, 4.6):
        window_row(m, wcx - ww / 2, wcx + ww / 2, y, wcz + wd / 2, 6, 1.4, 1.6, (0, 0, 1), "x")
        window_row(m, wcx - ww / 2, wcx + ww / 2, y, wcz - wd / 2, 6, 1.4, 1.6, (0, 0, -1), "x")
    # small tower at the left end of the hangar front
    tower(m, xh0 - 3.0, zf - 3.0 - 1.0, 6.0, 6.0, 14.0, 3)
    return m


def transmitter_site():
    """Edmonton radio transmitter site (118 Ave / 156 St, ~1950s): office/transmitter building, shed and red/white masts.

    Local frame: +Z = heading (front), +X = right; building long axis along X.  Layout read off the radiocom.ca photo.
    """
    m = Mesh()
    bw, bd, bh = 26.0, 11.0, 4.5
    m.box(-bw / 2, bw / 2, 0, bh, -bd / 2, bd / 2, WHITE, top=False)
    m.gable(-bw / 2, bw / 2, bh, 2.2, -bd / 2, bd / 2, along_z=False, sw_roof=RED, sw_wall=WHITE)
    window_row(m, -bw / 2, bw / 2, 1.3, bd / 2, 7, 1.3, 1.4, (0, 0, 1), "x")
    window_row(m, -bw / 2, bw / 2, 1.3, -bd / 2, 7, 1.3, 1.4, (0, 0, -1), "x")
    m.box(-44.0, -36.0, 0, 3.2, -4.0, 4.0, WHITE, top=False)  # shed to the left
    m.gable(-44.0, -36.0, 3.2, 1.6, -4.0, 4.0, along_z=False, sw_roof=RED, sw_wall=WHITE)
    # striped masts (x, z, height)
    masts = [(-58, 10, 45), (-30, -22, 35), (-12, -14, 38), (3, 8, 55), (14, -26, 36), (30, -30, 42),
             (44, 6, 48), (52, -18, 50), (66, -10, 44), (-48, -14, 30)]
    for mx, mz, mh in masts:
        w, seg, i, y = 0.45, 5.0, 0, 0.0
        while y < mh:
            y1 = min(y + seg, mh)
            m.box(mx - w, mx + w, y, y1, mz - w, mz + w, RED if i % 2 == 0 else WHITE, top=(y1 >= mh))
            y, i = y1, i + 1
    # tall centre mast carries a cross-arm
    m.box(-6.0, 6.0, 52.0, 52.5, 7.7, 8.3, METAL)
    return m


def wind_tee():
    """Wind tee on a post; the crossbar (head) is at +Z, so heading = the direction the tee points (into wind)."""
    m = Mesh()
    m.box(-0.12, 0.12, 0, 2.0, -0.12, 0.12, METAL)
    m.box(-0.35, 0.35, 2.0, 2.3, -3.0, 2.4, WHITE)
    m.box(-2.2, 2.2, 2.0, 2.3, 2.4, 3.0, WHITE)
    return m


# placement tweaks -------------------------------------------------------------------------
# Headings snapped parallel to the nearest runway/taxiway (the 1944-photo headings were ~6-10 deg off).
HEADINGS = [("hangar 11", 0.0), ("usaaf hangar t1", 0.0), ("usaaf hangar t2", 0.0),
            ("bcatp hangar row", 138.0), ("1938 arched hangar", 57.78), ("administration building", -3.6),
            ("north hangar complex", -1.0), ("north complex", -1.0)]
# (east, north) metre shifts to clear taxiways (north complex vs taxiway III; row A vs taxiway X)
SHIFTS = [("north hangar complex: bay 1", (0, -20)), ("north hangar complex: bay 2", (0, -20)),
          ("north complex: shop", (0, -25)), ("north complex: annex", (0, 10)), ("bcatp hangar row a", (-3.7, -1.5))]
# T4 stays as the sim's own generated building; hotels wait until the tower/wing split is known
SKIP = ("edmonton inn", "chateau louis", "usaaf hangar t4")
KX, KY = 66170.0, 111200.0
EXCL_MARGIN = 6.0
LANDMARK_BOX = (-27.4, 62.0, -22.0, 22.4)  # local x0, x1, z0, z1 of the landmark model


def lookup(table, low):
    for k, v in table:
        if k in low:
            return v
    return None


def footprint(lat, lon, hdg, x0, x1, z0, z1):
    """Rotated rectangle corners (lat, lon) for a model-local box; +Z = heading, +X = right."""
    h = math.radians(float(hdg))
    f, r = (math.sin(h), math.cos(h)), (math.cos(h), -math.sin(h))
    out = []
    for x, z in ((x0, z0), (x1, z0), (x1, z1), (x0, z1)):
        e, n = x * r[0] + z * f[0], x * r[1] + z * f[1]
        out.append((float(lat) + n / KY, float(lon) + e / KX))
    return out


def exclusion_xml(title, corners, nl):
    guid = "{" + str(uuid.uuid5(NS, "excl " + title)).upper() + "}"
    a = ('		<Attribute name="%s" guid="{%s}" type="%s" value="%s"/>')
    lines = ['	<Polygon version="0.4.0" displayName="No generated buildings: %s" parentGroupID="6" altitude="667.68023681640625">' % title.replace('"', "'")[:60],
             a % ("UniqueGUID", "359C73E8-06BE-4FB2-ABCB-EC942F7761D0", "GUID", guid),
             a % ("ExcludeDetectedBuildings", "5C1A2387-1F07-47DF-A569-962CF6258E55", "UINT8", "1"),
             a % ("ExcludeOSMBuildings", "F3C2635D-9F2F-458F-8663-90B3837BED09", "UINT8", "1"),
             a % ("ExcludeMSBuildings", "F78A3074-8AD5-4B8B-92C4-C1C948BB7AA5", "UINT8", "1"),
             a % ("ExcludeTIN", "18B58CBF-AE02-4A19-8AA9-3809E8E73400", "UINT8", "1"),
             a % ("ExclusionFlags", "4CACC252-E6DC-419A-B20C-16EC601DF70E", "UINT32", "3")]
    lines += ['		<Vertex lat="%.14f" lon="%.14f"/>' % c for c in corners]
    lines.append("	</Polygon>")
    return nl.join(lines) + nl


def main():
    src = SRC.read_text(encoding="utf-8")
    blocks = re.findall(r"(<!--(?:(?!-->).)*-->)?\s*(<SceneryObject lat=\"([^\"]+)\" lon=\"([^\"]+)\"[^>]*?heading=\"([^\"]+)\"[^>]*>\s*"
                        r"<GenericBuilding[^>]*>\s*<RectangularBuilding roofType=\"(\w+)\" sizeX=\"(\d+)\" sizeZ=\"(\d+)\" "
                        r"sizeBottomY=\"(\d+)\"[^>]*?sizeRoofY=\"(\d+)\"[^>]*/>)", src, re.S)
    write_palette(MODELLIB / "texture" / "cyxd_palette.png")
    out, excl, made = [], [], {}
    for com, _full, lat, lon, hdg, roof, sx, sz, h, rh in blocks:
        title = re.sub(r"\s+", " ", com.strip("<!->  ")) if com else ""
        low = title.lower()
        if "removed from cyxd" in low:
            title, low = "Hangar 14 (BCATP 1942): OSM way 230718920 footprint 91 x 100 m incl. lean-tos, axis-aligned", "hangar 14"
        if any(k in low for k in SKIP) or any(k in low for k in ("1938 hangar tower", "1937 office wing")):
            continue
        hh = lookup(HEADINGS, low)
        hdg = ("%g" % hh) if hh is not None else hdg
        sh = lookup(SHIFTS, low)
        if sh:
            lat, lon = "%.5f" % (float(lat) + sh[1] / KY), "%.5f" % (float(lon) + sh[0] / KX)
        if "1938 arched hangar" in low:
            name = "cyxd_hangar_1938_landmark"
            if name not in made:
                made[name] = hangar_1938().save(MODELLIB / name, name)
            guid = made[name]
            m_ = EXCL_MARGIN
            box = (LANDMARK_BOX[0] - m_, LANDMARK_BOX[1] + m_, LANDMARK_BOX[2] - m_, LANDMARK_BOX[3] + m_)
        else:
            name = f"cyxd_bldg_{roof.lower()}_{sx}x{sz}x{h}x{rh}"
            if name not in made:
                made[name] = simple_building(roof, float(sx), float(sz), float(h), float(rh)).save(MODELLIB / name, name)
            guid = made[name]
            m_ = EXCL_MARGIN
            box = (-float(sx) / 2 - m_, float(sx) / 2 + m_, -float(sz) / 2 - m_, float(sz) / 2 + m_)
        out.append((title or name, lat, lon, hdg, guid))
