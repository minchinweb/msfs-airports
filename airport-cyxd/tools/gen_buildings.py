    zb_ = z1 - REC
    m.poly([(xl, 0.5, z1), (dl, 0.5, zb_), (dl, FL, zb_), (xl, FL, z1)], PANEL, (xl - 4, 2.0, z1 - 4))  # -X angled panel, carries the sign
