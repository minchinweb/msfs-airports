"""Generate CYXD historic building models (glTF ModelLib) and their placement XML.

Reads  docs/cyxd/historic-buildings-genericbuilding.xml  (old GenericBuilding placements; source of truth
for position/heading/size), writes
  airport-cyxd/PackageSources/modelLib/<name>/<name>.{gltf,bin,xml}
  airport-cyxd/PackageSources/modelLib/texture/cyxd_palette.png(.xml)
and replaces the block between the BEGIN/END markers in CYXD.xml with LibraryObject placements.

Run:  python -I airport-cyxd/tools/gen_buildings.py   (from the repo root)

Model frame: origin on the ground at the footprint centre, Y up, +Z = object heading direction.
Hotels (Edmonton Inn, Chateau Louis) are skipped on purpose.
"""
import json, math, re, struct, uuid, zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs/cyxd/historic-buildings-genericbuilding.xml"
CYXD = ROOT / "airport-cyxd/PackageSources/Scenery/airport-cyxd/CYXD.xml"
MODELLIB = ROOT / "airport-cyxd/PackageSources/modelLib"
NS = uuid.UUID("5d0c6c7e-0c1d-4a53-9b6e-0c7d00000001")
BEGIN = "<!-- BEGIN historic buildings (generated by airport-cyxd/tools/gen_buildings.py) -->"
END = "<!-- END historic buildings -->"

# palette swatches (u index) -----------------------------------------------------------------
WALL, ROOF, METAL, DARK, BRICK, TRIM, RED, WHITE, GREY, SALMON, BLUE, YELLOW, GLASS, DGREY, CREAM, NAVY, PANEL, PBLUE, SLATE, DOORG = range(20)
PALETTE = [(178, 172, 160), (70, 66, 64), (122, 130, 130), (38, 40, 46), (150, 88, 72), (204, 200, 190), (196, 52, 40), (236, 234, 230),
           (168, 175, 170), (214, 122, 104), (28, 86, 160), (244, 204, 40), (48, 66, 76), (96, 100, 104),
           (214, 208, 190), (46, 60, 84), (228, 224, 212),
           (150, 186, 214), (96, 118, 140), (196, 192, 182)]
SW = 16


def write_palette(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    w, h = SW * len(PALETTE), SW
    raw = b"".join(b"\x00" + b"".join(bytes(PALETTE[x // SW]) for x in range(w)) for _ in range(h))

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) \
        + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.write_bytes(png)
    path.with_name(path.name + ".xml").write_text(
        '<BitmapConfiguration>\n\t<BitmapSlot>MTL_BITMAP_DECAL0</BitmapSlot>\n</BitmapConfiguration>\n')


TEX_T = 1.28  # metres per texture tile (8 clapboards / 8 shingle rows)
TEX_NAMES = ("siding", "shingle_red", "shingle_grey", "ribbed", "ribbed_blue")


def _png(path, w, h, px):
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    raw = b"".join(b"\x00" + b"".join(bytes(px[y][x]) for x in range(w)) for y in range(h))
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))
    path.with_name(path.name + ".xml").write_text(
        '<BitmapConfiguration>\n\t<BitmapSlot>MTL_BITMAP_DECAL0</BitmapSlot>\n</BitmapConfiguration>\n')


def write_textures(folder):
    """Procedural tileable 128 x 128 textures: clapboard siding and red/grey asphalt shingles (fixed seed, deterministic)."""
    import random
    folder.mkdir(parents=True, exist_ok=True)
    clamp = lambda v: max(0, min(255, int(v)))
    rnd = random.Random(1940)
    # clapboard: 8 boards of 16 px, lit top edge, shadow line at the lap
    base = (204, 200, 188)
    px = []
    for y in range(128):
        b, r = divmod(y, 16)
        bt = random.Random(b).uniform(-6, 6)
        edge = 16 if r == 0 else (-34 if r >= 14 else (-12 if r >= 12 else 0))
        px.append([tuple(clamp(base[c] + bt + edge + rnd.uniform(-5, 5)) for c in range(3)) for x in range(128)])
    _png(folder / "cyxd_siding.png", 128, 128, px)
    # ribbed metal cladding: vertical ribs every 16 px (cream, pale blue)
    for name, base in (("ribbed", (214, 208, 190)), ("ribbed_blue", (150, 186, 214))):
        px = []
        for y in range(128):
            line = []
            for x in range(128):
                rx = x % 16
                d = 14 if rx < 2 else (-24 if rx >= 13 else (-8 if rx >= 11 else 0))
                line.append(tuple(clamp(base[c] + d + random.Random(x // 16).uniform(-5, 5) + rnd.uniform(-4, 4)) for c in range(3)))
            px.append(line)
        _png(folder / ("cyxd_%s.png" % name), 128, 128, px)
    # shingles: 16 px rows, 32 px tabs, half-tab stagger, dark joints and shadow under each course
    for name, base in (("shingle_red", (150, 66, 52)), ("shingle_grey", (98, 98, 102))):
        px = []
        for y in range(128):
            row, r = divmod(y, 16)
            off = 16 if row % 2 else 0
            line = []
            for x in range(128):
                tab = ((x + off) % 128) // 32
                tx = (x + off) % 32
                tb = random.Random(row * 7 + tab).uniform(-12, 12)
                d = -40 if r >= 14 else (-18 if r >= 12 else 0)
                if tx in (0, 1):
                    d -= 30
                line.append(tuple(clamp(base[c] + tb + d + rnd.uniform(-7, 7)) for c in range(3)))
            px.append(line)
        _png(folder / ("cyxd_%s.png" % name), 128, 128, px)


# mesh builder ------------------------------------------------------------------------------
class Mesh:
    def __init__(self, textured=False):
        self.pos, self.nrm, self.uv, self.idx = [], [], [], []
        self.tri_mat = []  # material key per triangle ("flat" = palette swatch, else a TEX_NAMES entry)
        self.textured = textured

    def poly(self, pts, sw, centre):
        """Planar convex polygon, wound/flipped so the normal points away from `centre`."""
        a, b, c = pts[0], pts[1], pts[2]
        u = [b[i] - a[i] for i in range(3)]
        v = [c[i] - a[i] for i in range(3)]
        n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]]
        cen = [sum(p[i] for p in pts) / len(pts) for i in range(3)]
        if sum(n[i] * (cen[i] - centre[i]) for i in range(3)) < 0:
            pts = pts[::-1]
            n = [-x for x in n]
        ln = math.sqrt(sum(x * x for x in n)) or 1.0
        n = [x / ln for x in n]
        base = len(self.pos)
        uvp = ((sw + 0.5) / len(PALETTE), 0.5)
        key = "flat"
        if self.textured:
            vertical = abs(n[1]) < 0.5
            if vertical and sw == CREAM:
                key = "ribbed"
            elif vertical and sw == PBLUE:
                key = "ribbed_blue"
            elif vertical and sw in (WALL, WHITE, TRIM):
                key = "siding"
            elif not vertical and sw == RED:
                key = "shingle_red"
            elif not vertical and sw in (ROOF, DARK):
                key = "shingle_grey"
        if key != "flat":
            ua = (n[2], 0.0, -n[0])  # horizontal, in the surface plane
            ul = math.hypot(ua[0], ua[2])
            ua = (ua[0] / ul, 0.0, ua[2] / ul) if ul > 1e-6 else (1.0, 0.0, 0.0)
            va = (n[1] * ua[2] - n[2] * ua[1], n[2] * ua[0] - n[0] * ua[2], n[0] * ua[1] - n[1] * ua[0])
        for p in pts:
            self.pos.append(p)
            self.nrm.append(n)
            if key == "flat":
                self.uv.append(uvp)
            else:
                self.uv.append((sum(p[i] * ua[i] for i in range(3)) / TEX_T, -sum(p[i] * va[i] for i in range(3)) / TEX_T))
        for i in range(1, len(pts) - 1):
            self.idx += [base, base + i, base + i + 1]
            self.tri_mat.append(key)

    def box(self, x0, x1, y0, y1, z0, z1, sw, top=True):
        c = ((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2)
        P = lambda x, y, z: (x, y, z)
        self.poly([P(x0, y0, z0), P(x1, y0, z0), P(x1, y1, z0), P(x0, y1, z0)], sw, c)
        self.poly([P(x0, y0, z1), P(x1, y0, z1), P(x1, y1, z1), P(x0, y1, z1)], sw, c)
        self.poly([P(x0, y0, z0), P(x0, y0, z1), P(x0, y1, z1), P(x0, y1, z0)], sw, c)
        self.poly([P(x1, y0, z0), P(x1, y0, z1), P(x1, y1, z1), P(x1, y1, z0)], sw, c)
        if top:
            self.poly([P(x0, y1, z0), P(x1, y1, z0), P(x1, y1, z1), P(x0, y1, z1)], sw, c)

    def gable(self, x0, x1, y0, ridge_h, z0, z1, along_z, sw_roof, sw_wall):
        """Gable roof on top of a box top at y0; ridge parallel to Z if along_z else X."""
        P = lambda x, y, z: (x, y, z)
        yr = y0 + ridge_h
        if along_z:
            xm = (x0 + x1) / 2
            c = (xm, y0, (z0 + z1) / 2)
            self.poly([P(x0, y0, z0), P(xm, yr, z0), P(xm, yr, z1), P(x0, y0, z1)], sw_roof, (xm, y0 - 5, c[2]))
            self.poly([P(x1, y0, z0), P(x1, y0, z1), P(xm, yr, z1), P(xm, yr, z0)], sw_roof, (xm, y0 - 5, c[2]))
            self.poly([P(x0, y0, z0), P(x1, y0, z0), P(xm, yr, z0)], sw_wall, (xm, y0 - 1, c[2]))
            self.poly([P(x0, y0, z1), P(x1, y0, z1), P(xm, yr, z1)], sw_wall, (xm, y0 - 1, c[2]))
        else:
            zm = (z0 + z1) / 2
            c = ((x0 + x1) / 2, y0, zm)
            self.poly([P(x0, y0, z0), P(x0, yr, zm), P(x1, yr, zm), P(x1, y0, z0)], sw_roof, (c[0], y0 - 5, zm))
            self.poly([P(x0, y0, z1), P(x1, y0, z1), P(x1, yr, zm), P(x0, yr, zm)], sw_roof, (c[0], y0 - 5, zm))
            self.poly([P(x0, y0, z0), P(x0, y0, z1), P(x0, yr, zm)], sw_wall, (c[0] + 1, y0 - 1, zm))
            self.poly([P(x1, y0, z0), P(x1, y0, z1), P(x1, yr, zm)], sw_wall, (c[0] - 1, y0 - 1, zm))

    def window(self, face, origin, u_axis, w, h, off=0.06):
        """Dark window quad lying on a wall: origin = lower-left corner on the wall, face = outward normal."""
        o = [origin[i] + face[i] * off for i in range(3)]
        up = (0, 1, 0)
        p = [tuple(o[i] for i in range(3)),
             tuple(o[i] + u_axis[i] * w for i in range(3)),
             tuple(o[i] + u_axis[i] * w + up[i] * h for i in range(3)),
             tuple(o[i] + up[i] * h for i in range(3))]
        centre = tuple(p[0][i] - face[i] for i in range(3))
        self.poly(p, DARK, centre)

    def mirror_x(self):
        """Flip east-west: the sim places model +X to the west of the object heading, so site models built in
        (east, north) metres are mirrored once at the end (negate X, flip winding)."""
        self.pos = [(-x, y, z) for x, y, z in self.pos]
        self.nrm = [(-x, y, z) for x, y, z in self.nrm]
        self.idx = [i for t in range(0, len(self.idx), 3) for i in (self.idx[t], self.idx[t + 2], self.idx[t + 1])]

    def save(self, folder, name):
        folder.mkdir(parents=True, exist_ok=True)
        n = len(self.pos)
        assert n < 65535
        pos = b"".join(struct.pack("<3f", *p) for p in self.pos)
        nrm = b"".join(struct.pack("<3f", *p) for p in self.nrm)
        uv = b"".join(struct.pack("<2f", *p) for p in self.uv)
        keys = [k for k in ("flat",) + TEX_NAMES if k in self.tri_mat] or ["flat"]
        blob = pos + nrm + uv
        views = [{"buffer": 0, "byteOffset": 0, "byteLength": len(pos)},
                 {"buffer": 0, "byteOffset": len(pos), "byteLength": len(nrm)},
                 {"buffer": 0, "byteOffset": len(pos) + len(nrm), "byteLength": len(uv)}]
        mn = [min(p[i] for p in self.pos) for i in range(3)]
        mx = [max(p[i] for p in self.pos) for i in range(3)]
        accs = [{"bufferView": 0, "componentType": 5126, "count": n, "type": "VEC3", "min": mn, "max": mx},
                {"bufferView": 1, "componentType": 5126, "count": n, "type": "VEC3"},
                {"bufferView": 2, "componentType": 5126, "count": n, "type": "VEC2"}]
        prims = []
        for mi, k in enumerate(keys):
            tris = [self.idx[3 * t:3 * t + 3] for t in range(len(self.tri_mat)) if self.tri_mat[t] == k]
            ib = b"".join(struct.pack("<H", i) for tri in tris for i in tri)
            cnt = len(tris) * 3
            if len(ib) % 4:
                ib += b"\x00\x00"
            views.append({"buffer": 0, "byteOffset": len(blob), "byteLength": len(tris) * 6})
            blob += ib
            accs.append({"bufferView": len(views) - 1, "componentType": 5123, "count": cnt, "type": "SCALAR"})
            prims.append({"attributes": {"POSITION": 0, "NORMAL": 1, "TEXCOORD_0": 2}, "indices": len(accs) - 1, "mode": 4, "material": mi})
        (folder / f"{name}.bin").write_bytes(blob)
        mats, texs, imgs = [], [], []
        for k in keys:
            uri = "cyxd_palette.png" if k == "flat" else "cyxd_%s.png" % k
            imgs.append({"uri": uri})
            texs.append({"sampler": 0 if k == "flat" else 1, "source": len(imgs) - 1})
            mats.append({"name": "cyxd_" + k, "pbrMetallicRoughness": {
                "baseColorTexture": {"index": len(texs) - 1}, "metallicFactor": 0.0, "roughnessFactor": 0.9}})
        g = {
            "asset": {"version": "2.0", "generator": "airport-cyxd/tools/gen_buildings.py",
                      "extensions": {"ASOBO_normal_map_convention": {"tangent_space_convention": "DirectX"}}},
            "extensionsUsed": ["ASOBO_normal_map_convention"],
            "scene": 0, "scenes": [{"nodes": [0]}],
            "nodes": [{"mesh": 0, "name": name}],
            "meshes": [{"name": name, "primitives": prims}],
            "materials": mats, "textures": texs,
            "samplers": [{"magFilter": 9728, "minFilter": 9728}, {"magFilter": 9729, "minFilter": 9987, "wrapS": 10497, "wrapT": 10497}],
            "images": imgs, "accessors": accs, "bufferViews": views,
            "buffers": [{"uri": f"{name}.bin", "byteLength": len(blob)}],
        }
        (folder / f"{name}.gltf").write_text(json.dumps(g, indent=1))
        guid = "{" + str(uuid.uuid5(NS, name)).upper() + "}"
        (folder / f"{name}.xml").write_text(
            f'<?xml version="1.0" encoding="utf-8"?>\n<ModelInfo guid="{guid}" version="1.1">\n'
            f'\t<LODS>\n\t\t<LOD minSize="0" ModelFile="{name}.gltf"/>\n\t</LODS>\n</ModelInfo>\n')
        return guid


