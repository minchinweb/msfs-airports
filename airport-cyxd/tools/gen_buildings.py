def simple_building(roof, sx, sz, h, rh):
    m = Mesh()
    m.box(-sx / 2, sx / 2, 0, h, -sz / 2, sz / 2, WALL, top=(roof != "RIDGE"))
    if roof == "RIDGE":
        # ridge along the longer horizontal axis
        m.gable(-sx / 2, sx / 2, h, rh, -sz / 2, sz / 2, along_z=(sz >= sx), sw_roof=ROOF, sw_wall=WALL)
    return m


def window_row(m, x0, x1, y, z, count, w, h, face, axis):
    """Row of `count` windows across a wall between x0..x1 (along `axis`), at height y, on plane z."""
    span = x1 - x0
    gap = (span - count * w) / (count + 1)
    for i in range(count):
        s = x0 + gap + i * (w + gap)
        if axis == "x":
            m.window(face, (s, y, z), (1, 0, 0), w, h)
        else:  # along z: wall plane is x=z param
            m.window(face, (z, y, s), (0, 0, 1), w, h)


def tower(m, cx, cz, sx, sz, h, floors, front=(0, 0, 1)):
    x0, x1, z0, z1 = cx - sx / 2, cx + sx / 2, cz - sz / 2, cz + sz / 2
    m.box(x0, x1, 0, h, z0, z1, WALL)
    m.box(x0 - 0.4, x1 + 0.4, h, h + 1.0, z0 - 0.4, z1 + 0.4, TRIM)  # parapet cap
    fh = h / floors
    for f in range(floors):
        y = f * fh + fh * 0.35
        if f == 0:
            continue
        window_row(m, x0, x1, y, z1, 2, 1.2, 1.8, (0, 0, 1), "x")
        window_row(m, x0, x1, y, z0, 2, 1.2, 1.8, (0, 0, -1), "x")
        window_row(m, z0, z1, y, x1, 2, 1.2, 1.8, (1, 0, 0), "z")
        window_row(m, z0, z1, y, x0, 2, 1.2, 1.8, (-1, 0, 0), "z")


def hangar_1938():
    """1938 arched hangar + main tower + small tower + office wing (EA-160-398/402/466/1331/1332, 1944 aerial).

    Local frame: +Z = front (doors / landmark face, heading direction), +X = right of the front as seen from the front.
    Hangar centred at the origin; tower and wing sit to its right along the front, small tower to its left.
    """
    m = Mesh()
    span, length, wall, rise = 42.0, 44.0, 7.0, 6.0
    xh0, xh1, zf, zb = -span / 2, span / 2, length / 2, -length / 2
    # walls
    m.box(xh0, xh1, 0, wall, zb, zf, METAL, top=False)
    # barrel vault
    n = 14
    prof = []
    for i in range(n + 1):
        a = math.pi * i / n
        prof.append((math.cos(a) * span / 2, wall + math.sin(a) * rise))
    prof = prof[::-1]  # left to right
    cen = (0, wall, 0)
    for i in range(n):
        (xa, ya), (xb, yb) = prof[i], prof[i + 1]
        m.poly([(xa, ya, zb), (xb, yb, zb), (xb, yb, zf), (xa, ya, zf)], METAL, (0, wall - 3, 0))
    # end arches (front and back)
    for z, sw in ((zf, METAL), (zb, METAL)):
        m.poly([(xh0, wall, z)] + [(x, y, z) for x, y in prof] + [(xh1, wall, z)], sw, (0, wall, 0))
    # big front doors (open, dark) and side windows
    m.poly([(-16, 0.0, zf + 0.08), (16, 0.0, zf + 0.08), (16, 7.0, zf + 0.08), (-16, 7.0, zf + 0.08)], DARK, (0, 3, 0))
    m.poly([(-16, 7.0, zf + 0.08), (16, 7.0, zf + 0.08), (11, 11.0, zf + 0.08), (-11, 11.0, zf + 0.08)], DARK, (0, 5, 0))
    for sgn in (-1, 1):
        for i in range(6):
            z = zb + 4 + i * 6.5
            m.window((sgn, 0, 0), (sgn * (span / 2), 3.2, z), (0, 0, 1), 3.0, 1.6)
    # main tower, flush with front face, right of hangar
    tw, td, th = 11.0, 11.0, 22.0
    tcx, tcz = xh1 + tw / 2, zf - td / 2
    tower(m, tcx, tcz, tw, td, th, 5)
    # office wing continues to the right, two storeys, hip-ish gable roof along X
    ww, wd, wh = 30.0, 13.0, 8.0
    wcx, wcz = tcx + tw / 2 + ww / 2, zf - wd / 2 - 1.0
    m.box(wcx - ww / 2, wcx + ww / 2, 0, wh, wcz - wd / 2, wcz + wd / 2, WALL, top=False)
    m.gable(wcx - ww / 2, wcx + ww / 2, wh, 3.5, wcz - wd / 2, wcz + wd / 2, along_z=False, sw_roof=ROOF, sw_wall=WALL)
    for y in (1.2, 4.6):
        window_row(m, wcx - ww / 2, wcx + ww / 2, y, wcz + wd / 2, 6, 1.4, 1.6, (0, 0, 1), "x")
        window_row(m, wcx - ww / 2, wcx + ww / 2, y, wcz - wd / 2, 6, 1.4, 1.6, (0, 0, -1), "x")
    # small tower at the left end of the hangar front
    tower(m, xh0 - 3.0, zf - 3.0 - 1.0, 6.0, 6.0, 14.0, 3)
    return m


def transmitter_site():
    """Edmonton radio transmitter site (118 Ave / 156 St, ~1950s): office/transmitter building, shed and red/white masts.

    Local frame: +Z = heading (front), +X = right; building long axis along X.  Layout read off the radiocom.ca photo.
    """
    m = Mesh(textured=True)
    bw, bd, bh = 26.0, 11.0, 4.5
    m.box(-bw / 2, bw / 2, 0, bh, -bd / 2, bd / 2, WHITE, top=False)
    m.gable(-bw / 2, bw / 2, bh, 2.2, -bd / 2, bd / 2, along_z=False, sw_roof=RED, sw_wall=WHITE)
    window_row(m, -bw / 2, bw / 2, 1.3, bd / 2, 7, 1.3, 1.4, (0, 0, 1), "x")
    window_row(m, -bw / 2, bw / 2, 1.3, -bd / 2, 7, 1.3, 1.4, (0, 0, -1), "x")
    m.box(-44.0, -36.0, 0, 3.2, -4.0, 4.0, WHITE, top=False)  # shed to the left
    m.gable(-44.0, -36.0, 3.2, 1.6, -4.0, 4.0, along_z=False, sw_roof=RED, sw_wall=WHITE)
    # striped masts (x, z, height)
    masts = [(-58, 10, 45), (-30, -22, 35), (-12, -14, 38), (3, 8, 55), (14, -26, 36), (30, -30, 42),
             (44, 6, 48), (52, -18, 50), (66, -10, 44), (-48, -14, 30)]
    for mx, mz, mh in masts:
        w, seg, i, y = 0.45, 5.0, 0, 0.0
        while y < mh:
            y1 = min(y + seg, mh)
            m.box(mx - w, mx + w, y, y1, mz - w, mz + w, RED if i % 2 == 0 else WHITE, top=(y1 >= mh))
            y, i = y1, i + 1
    # tall centre mast carries a cross-arm
    m.box(-6.0, 6.0, 52.0, 52.5, 7.7, 8.3, METAL)
