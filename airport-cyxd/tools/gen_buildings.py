    for xd in (e[3] - 0.6, e[4] - 0.6):  # landside entrances
        m.window((0, 0, -1), (xd, 0.0, z0), (1, 0, 0), 1.2, 2.2, off=0.14)
    # roof gear: HF antenna pad and a whip mast over the NW part
