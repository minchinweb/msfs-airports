            line = []
            for x in range(128):
                tab = ((x + off) % 128) // 32
                tx = (x + off) % 32
                tb = random.Random(row * 7 + tab).uniform(-12, 12)
                d = -40 if r >= 14 else (-18 if r >= 12 else 0)
