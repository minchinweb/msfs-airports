def ring(hx, hz, c, cx=0.0, cz=0.0):
    """Octagon (rectangle hx x hz half-sizes with corners chamfered by c), counter-clockwise."""
    return [(cx - hx + c, cz - hz), (cx + hx - c, cz - hz), (cx + hx, cz - hz + c), (cx + hx, cz + hz - c),
            (cx + hx - c, cz + hz), (cx - hx + c, cz + hz), (cx - hx, cz + hz - c), (cx - hx, cz - hz + c)]


def frustum(m, r0, y0, r1, y1, sw, top=False, bottom=False):
    """Prism/frustum between two similar rings (x, z) at heights y0, y1."""
    n = len(r0)
    cen = (sum(x for x, z in r0) / n, (y0 + y1) / 2, sum(z for x, z in r0) / n)
    for i in range(n):
        a0, b0, a1, b1 = r0[i], r0[(i + 1) % n], r1[i], r1[(i + 1) % n]
        m.poly([(a0[0], y0, a0[1]), (b0[0], y0, b0[1]), (b1[0], y1, b1[1]), (a1[0], y1, a1[1])], sw, cen)
    if top:
        m.poly([(x, y1, z) for x, z in r1], sw, cen)
    if bottom:
        m.poly([(x, y0, z) for x, z in r0], sw, cen)


def rail_ring(m, r, y_top, sw, posts_every=2.0):
    """Handrail (top + mid rail + posts) around a ring."""
    n = len(r)
    for i in range(n):
        a, b = r[i], r[(i + 1) % n]
        obox(m, a, b, y_top - 0.05, y_top, 0.025, sw)
        obox(m, a, b, y_top * 0 + y_top - 0.55, y_top - 0.5, 0.02, sw)
        k = max(1, int(math.hypot(b[0] - a[0], b[1] - a[1]) / posts_every))
        for j in range(k):
            q = (a[0] + (b[0] - a[0]) * j / k, a[1] + (b[1] - a[1]) * j / k)
            m.box(q[0] - 0.03, q[0] + 0.03, y_top - 1.05, y_top, q[1] - 0.03, q[1] + 0.03, sw)


SEGS = {"0": "abcdef", "1": "bc", "2": "abged", "3": "abgcd", "4": "fgbc", "5": "afgcd", "6": "afgedc", "7": "abc", "8": "abcdefg", "9": "abcdfg"}


def number_disc(m, cx, cy, cz, n, r, text):
    """Blue disc with yellow seven-segment numerals on a vertical wall (n = outward horizontal normal (nx, nz))."""
    ux, uz = -n[1], n[0]  # reading direction seen from outside; the (east, up, north) frame is left-handed, so u = n x up
    pt = lambda u, v, off: (cx + ux * u + n[0] * off, cy + v, cz + uz * u + n[1] * off)
    centre = (cx - n[0], cy, cz - n[1])
    D = 0.16  # roundel stands 16 cm off the wall; numerals another 5 cm
    ring_pts = [(r * math.cos(2 * math.pi * k / 24), r * math.sin(2 * math.pi * k / 24)) for k in range(24)]
    m.poly([pt(u, v, D) for u, v in ring_pts], BLUE, centre)
    for k in range(24):  # rim
        (u0, v0), (u1, v1) = ring_pts[k], ring_pts[(k + 1) % 24]
        m.poly([pt(u0, v0, 0.0), pt(u1, v1, 0.0), pt(u1, v1, D), pt(u0, v0, D)], WHITE, (cx, cy, cz))

    def wbox(u0, u1, v0, v1, o0, o1, sw):
        bc = pt((u0 + u1) / 2, (v0 + v1) / 2, (o0 + o1) / 2)
        m.poly([pt(u0, v0, o1), pt(u1, v0, o1), pt(u1, v1, o1), pt(u0, v1, o1)], sw, bc)
        for (a_, b_), (c_, d_) in (((u0, v0), (u1, v0)), ((u1, v0), (u1, v1)), ((u1, v1), (u0, v1)), ((u0, v1), (u0, v0))):
            m.poly([pt(a_, b_, o0), pt(c_, d_, o0), pt(c_, d_, o1), pt(a_, b_, o1)], sw, bc)
    W, H, t = 0.5 * r, 0.95 * r, 0.14 * r
    boxes = {"a": (0, W, H - t, H), "b": (W - t, W, H / 2, H), "c": (W - t, W, 0, H / 2), "d": (0, W, 0, t),
             "e": (0, t, 0, H / 2), "f": (0, t, H / 2, H), "g": (0, W, H / 2 - t / 2, H / 2 + t / 2)}
    total = len(text) * W + (len(text) - 1) * 0.18 * r
    for i, ch in enumerate(text):
        u0 = -total / 2 + i * (W + 0.18 * r)
        for sg in SEGS[ch]:
            a, b, c0, c1 = boxes[sg]
            wbox(u0 + a, u0 + b, c0 - H / 2, c1 - H / 2, D, D + 0.05, YELLOW)


