            if sgn > 0:
                if k == 2:
                    continue  # entrance bay handled below
                if k == 5:
                    xa = x0 + PASS + 0.45
                if xb - xa > 1.0:
                    m.window(face, (xa, 0.7, zf), (1, 0, 0), xb - xa, 2.8, off=0.14)
            else:
                for dx in (-1.4, 0.2):
                    xc = (xa + xb) / 2 + dx
