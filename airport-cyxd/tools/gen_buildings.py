def simple_building(roof, sx, sz, h, rh):
    m = Mesh()
    m.box(-sx / 2, sx / 2, 0, h, -sz / 2, sz / 2, WALL, top=(roof != "RIDGE"))
    if roof == "RIDGE":
        # ridge along the longer horizontal axis
        m.gable(-sx / 2, sx / 2, h, rh, -sz / 2, sz / 2, along_z=(sz >= sx), sw_roof=ROOF, sw_wall=WALL)
    return m


def window_row(m, x0, x1, y, z, count, w, h, face, axis):
    """Row of `count` windows across a wall between x0..x1 (along `axis`), at height y, on plane z."""
    span = x1 - x0
    gap = (span - count * w) / (count + 1)
    for i in range(count):
        s = x0 + gap + i * (w + gap)
        if axis == "x":
            m.window(face, (s, y, z), (1, 0, 0), w, h)
        else:  # along z: wall plane is x=z param
            m.window(face, (z, y, s), (0, 0, 1), w, h)


def tower(m, cx, cz, sx, sz, h, floors, front=(0, 0, 1)):
    x0, x1, z0, z1 = cx - sx / 2, cx + sx / 2, cz - sz / 2, cz + sz / 2
    m.box(x0, x1, 0, h, z0, z1, WALL)
    m.box(x0 - 0.4, x1 + 0.4, h, h + 1.0, z0 - 0.4, z1 + 0.4, TRIM)  # parapet cap
    fh = h / floors
    for f in range(floors):
        y = f * fh + fh * 0.35
        if f == 0:
            continue
        window_row(m, x0, x1, y, z1, 2, 1.2, 1.8, (0, 0, 1), "x")
        window_row(m, x0, x1, y, z0, 2, 1.2, 1.8, (0, 0, -1), "x")
        window_row(m, z0, z1, y, x1, 2, 1.2, 1.8, (1, 0, 0), "z")
        window_row(m, z0, z1, y, x0, 2, 1.2, 1.8, (-1, 0, 0), "z")


def hangar_1938():
    """1938 arched hangar + main tower + small tower + office wing (EA-160-398/402/466/1331/1332, 1944 aerial).

    Local frame: +Z = front (doors / landmark face, heading direction), +X = right of the front as seen from the front.
    Hangar centred at the origin; tower and wing sit to its right along the front, small tower to its left.
    """
    m = Mesh()
    span, length, wall, rise = 42.0, 44.0, 7.0, 6.0
    xh0, xh1, zf, zb = -span / 2, span / 2, length / 2, -length / 2
    # walls
    m.box(xh0, xh1, 0, wall, zb, zf, METAL, top=False)
    # barrel vault
    n = 14
    prof = []
    for i in range(n + 1):
        a = math.pi * i / n
        prof.append((math.cos(a) * span / 2, wall + math.sin(a) * rise))
    prof = prof[::-1]  # left to right
    cen = (0, wall, 0)
    for i in range(n):
        (xa, ya), (xb, yb) = prof[i], prof[i + 1]
        m.poly([(xa, ya, zb), (xb, yb, zb), (xb, yb, zf), (xa, ya, zf)], METAL, (0, wall - 3, 0))
    # end arches (front and back)
    for z, sw in ((zf, METAL), (zb, METAL)):
        m.poly([(xh0, wall, z)] + [(x, y, z) for x, y in prof] + [(xh1, wall, z)], sw, (0, wall, 0))
    # big front doors (open, dark) and side windows
