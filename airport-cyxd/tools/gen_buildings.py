def lookup(table, low):
    for k, v in table:
        if k in low:
            return v
    return None


def footprint(lat, lon, hdg, x0, x1, z0, z1):
    """Rotated rectangle corners (lat, lon) for a model-local box; +Z = heading, +X = right."""
    h = math.radians(float(hdg))
    f, r = (math.sin(h), math.cos(h)), (math.cos(h), -math.sin(h))
    out = []
    for x, z in ((x0, z0), (x1, z0), (x1, z1), (x0, z1)):
        e, n = x * r[0] + z * f[0], x * r[1] + z * f[1]
        out.append((float(lat) + n / KY, float(lon) + e / KX))
    return out


