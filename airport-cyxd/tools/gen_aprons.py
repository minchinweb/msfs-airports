"""Extend the aprons up to each hangar's front (door) wall.  Preview:  python -I airport-cyxd/tools/gen_aprons.py
Write into CYXD.xml:  python -I airport-cyxd/tools/gen_aprons.py --write   (generated block between the BEGIN/END markers inside <Aprons>)
Door walls are per building (outward bearing, from each model's door wall), not the side nearest the runway.  Hangar 14 (museum) is skipped on purpose."""
import math
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

from shapely.geometry import LineString, Point, Polygon
from shapely.ops import nearest_points, unary_union

ROOT = Path(__file__).resolve().parents[2]
CYXD = ROOT / "airport-cyxd/PackageSources/Scenery/airport-cyxd/CYXD.xml"
KX, KY = 66170.0, 111200.0
MARGIN = 6.0  # the generator's exclusion margin around each footprint
BEGIN = "<!-- BEGIN hangar aprons (generated by airport-cyxd/tools/gen_aprons.py) -->"
END = "<!-- END hangar aprons -->"
SURFACE = "{85D02B2B-08A1-452E-AB07-6D5AE7F52884}"
LINK_W = 24.0     # width of a connecting strip to existing pavement
FORECOURT = 12.0  # depth in front of a door when no pavement lies straight ahead
# (title prefix, outward bearing of the door wall)
DOORS = [
    ("Hangar 4 (", 270), ("Hangar 5 (", 270), ("Hangar 6 (", 270), ("Hangar 7 (", 270),
    ("Hangar 8 (", 0), ("Hangar 11 (", 0), ("Hangar 18 (", 138), ("Hangar 39 (", 138),
    ("Hangar 40 (", 48), ("Hangar 21 (", 51), ("Second hangar", 57.78), ("Hangar 3 (", 270),
    ("Dark-blue gabled", 180), ("Hangar 19 (", 52), ("Hangar 20 (", 48),
    ("North hangar complex: two sawtooth", 180), ("North hangar complex: shop", 180), ("North hangar complex: annex", 180),
    ("North hangar complex: east bay 3", 180), ("North hangar complex: narrow", 180),
    ("Aerocentre", 48), ("Shell hangar", 48), ("Hangar 15 (", 138), ("Hangar 15 east wing", 48),
]
# held back until the user confirms the door wall (see STATUS.md: the shop and annex are advised against)
HOLD = ("Hangar 3 (", "Dark-blue gabled", "Second hangar", "North hangar complex: shop", "North hangar complex: annex")
DEPTH = {}  # fixed depths (none now; Hangar 38 is served by extending the hand-written Hangar 39 apron, groupIndex 2, 24 m to the SW)
GROW = {"Hangar 8 (": 6.0, "Hangar 11 (": 6.0, "Hangar 18 (": 4.0}  # apron grows out until this clearance (m) from the next building (user: almost to the hangar beyond / the tower)
TO_TAXI = ("Hangar 21 (",)  # runs out to the taxiway (terminal: jets)
TURN = {"Hangar 15 (": (18.0, 22.0)}  # forecourt depth, strip width: out of the door, then a turn to the taxiway (no strip through Hangar 14)
KEEP_CLEAR = ("Hangar 14 (",)  # museum: no apron towards it; a fence line stands between it and Hangar 15
KEEP_CLEAR_M = 12.0



def main():
    write = "--write" in sys.argv
    text = CYXD.read_text(encoding="utf-8")
    pat = r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\r?\n"
    text_clean = re.sub(pat, "", text, flags=re.S)  # checks run without the previous generated aprons
    root = ET.fromstring(text_clean)
    ap = root.find("Airport")
    lat0, lon0 = float(ap.get("lat")), float(ap.get("lon"))
    xy = lambda la, lo: ((float(lo) - lon0) * KX, (float(la) - lat0) * KY)
    pts = {p.get("index"): xy(p.get("lat"), p.get("lon")) for p in ap.findall("TaxiwayPoint")}
    taxi = unary_union([LineString([pts[t.get("start")], pts[t.get("end")]]).buffer(float(t.get("width")) / 2, cap_style=2)
                        for t in ap.findall("TaxiwayPath")
                        if t.get("type") == "TAXI" and t.get("start") in pts and t.get("end") in pts and pts[t.get("start")] != pts[t.get("end")]])
    aprons = unary_union([Polygon([xy(v.get("lat"), v.get("lon")) for v in a.findall("Vertex")]) for a in ap.iter("Apron")])
    pave = unary_union([taxi, aprons])
    rw = []
    for r in ap.findall("Runway"):
        cx, cy = xy(r.get("lat"), r.get("lon"))
        h = math.radians(float(r.get("heading")))
        f, rt = (math.sin(h), math.cos(h)), (math.cos(h), -math.sin(h))
        hl, hw = float(r.get("length")) / 2, float(r.get("width")) / 2 + 3
        rw.append(Polygon([(cx + a * rt[0] + b * f[0], cy + a * rt[1] + b * f[1]) for a, b in ((-hw, -hl), (hw, -hl), (hw, hl), (-hw, hl))]))
    runways = unary_union(rw)
    spots = [(xy(p.get("lat"), p.get("lon")), float(p.get("radius"))) for p in ap.iter("TaxiwayParking")]
    feet = {}
    for pl in root.iter("Polygon"):
        d = pl.get("displayName", "")
        if d.startswith("No generated buildings: "):
            p = Polygon([xy(v.get("lat"), v.get("lon")) for v in pl.findall("Vertex")])
            q = p.buffer(-MARGIN, join_style=2)
            feet[d[len("No generated buildings: "):]] = q if not q.is_empty else p
    out = []
    for prefix, brg in DOORS:
        if prefix in HOLD:
            continue
        key = [k for k in feet if k.startswith(prefix)]
        if not key:
            print("NO FOOTPRINT for", prefix)
            continue
        title = key[0]
        fp = feet[title]
        rect = fp.minimum_rotated_rectangle
        c = list(rect.exterior.coords)[:4]
        centre = rect.centroid
        want = (math.sin(math.radians(brg)), math.cos(math.radians(brg)))
        best = None
        for i in range(4):
            a, b = c[i], c[(i + 1) % 4]
            mid = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
            n = (mid[0] - centre.x, mid[1] - centre.y)
            L = math.hypot(*n)
            n = (n[0] / L, n[1] / L)
            s = n[0] * want[0] + n[1] * want[1]
            if best is None or s > best[0]:
                best = (s, a, b, n)
        _, a, b, n = best

        def ext(d):
            return Polygon([a, b, (b[0] + n[0] * d, b[1] + n[1] * d), (a[0] + n[0] * d, a[1] + n[1] * d)])
        mid = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
        avoid = unary_union([f2.buffer(KEEP_CLEAR_M) for t2, f2 in feet.items() if t2.startswith(KEEP_CLEAR)])
        ray_hit = next((k for k in range(0, 160) if pave.contains(Point(mid[0] + n[0] * k, mid[1] + n[1] * k))), None)
        if prefix in TURN:
            dep, wid = TURN[prefix]
            quad = ext(dep)
            tip = (mid[0] + n[0] * dep, mid[1] + n[1] * dep)
            tgt = nearest_points(Point(tip), pave.difference(avoid))[1]
            quad = unary_union([quad, LineString([tip, (tgt.x, tgt.y)]).buffer(wid / 2, cap_style=2)]).difference(avoid)
            mode = "forecourt %.0f m + turn %.0f m" % (dep, Point(tip).distance(tgt))
        elif prefix in TO_TAXI:
            dmax = 0
            for k in range(1, 11):
                p0 = (a[0] + (b[0] - a[0]) * k / 11, a[1] + (b[1] - a[1]) * k / 11)
                dmax = max(dmax, next((j for j in range(1, 200) if taxi.contains(Point(p0[0] + n[0] * j, p0[1] + n[1] * j))), 0))
            quad = ext(dmax + 3.0)
            mode = "to taxiway %.0f m" % dmax
        elif prefix in GROW:
            others = [f2.buffer(GROW[prefix]) for t2, f2 in feet.items() if t2 != title and not t2.startswith("Old terminal")]
            obst = unary_union(others)
            d = next((j for j in range(1, 200) if ext(j).intersects(obst)), 200) - 1
            quad = ext(d)
            mode = "grown %d m" % d
            if not quad.intersects(pave):
                near = nearest_points(quad, pave)
                lat = (-n[1], n[0])  # sideways along the door wall: the strip slides to the pavement, so the access is as wide as the strip
                t = (near[1].x - near[0].x) * lat[0] + (near[1].y - near[0].y) * lat[1]
                L, lw = abs(t), math.dist(a, b)
                from shapely import affinity
                quad = unary_union([quad, affinity.translate(quad, lat[0] * t, lat[1] * t)]).convex_hull
                mode += " + link %.0f m x %.0f m" % (L, lw)
        elif prefix in DEPTH:
            quad = ext(DEPTH[prefix])
            mode = "fixed %.0f m" % DEPTH[prefix]
        elif ray_hit is not None:
            quad = ext(max(ray_hit, 0.0) + 3.0)
            mode = "ray %d m" % ray_hit
        else:
            quad = ext(FORECOURT)
            near = nearest_points(quad, pave)
            quad = unary_union([quad, LineString([near[0], near[1]]).buffer(LINK_W / 2, cap_style=2)])
            mode = "forecourt %.0f m + link %.0f m" % (FORECOURT, near[0].distance(near[1]))
        new = quad.difference(pave).difference(fp)
        conf = []
        if new.intersects(runways):
            conf.append("RUNWAY")
        for t2, f2 in feet.items():
            if t2 != title and not t2.startswith("Old terminal") and new.intersects(f2.buffer(-0.5)):
                conf.append("bldg:" + t2[:22])
        for (sx, sy), r in spots:
            if new.intersects(Point(sx, sy).buffer(r * 0.9)):
                conf.append("parking")
                break
        print("%-34s brg %5.1f span %5.1f  %-34s new %6.0f m2  %s" % (title[:34], brg, math.dist(a, b), mode, new.area, ",".join(conf)))
        out.append((title, quad.difference(fp)))
    if not write:
        return
    lines = ["\t\t\t" + BEGIN]
    for title, q in out:
        for g in (q.geoms if hasattr(q, "geoms") else [q]):
            if g.is_empty or g.geom_type != "Polygon":
                continue
            lines.append("\t\t\t<!-- front-door apron: %s -->" % title.replace("--", "-"))
            lines.append('\t\t\t<Apron parentGroupID="3" surface="%s" drawSurface="TRUE" drawDetail="TRUE" localUV="TRUE" stretchUV="TRUE" flipUV="FALSE" priority="1" tiling="25.000000" heading="0.000000" falloff="0.100000" opacity="255" groundMerging="TRUE" excludeVegetationAround="TRUE" excludeVegetationInside="TRUE" isRectangle="FALSE">' % SURFACE)
            for x, y in list(g.exterior.coords)[:-1]:
                lines.append('\t\t\t\t<Vertex lat="%.14f" lon="%.14f"/>' % (lat0 + y / KY, lon0 + x / KX))
            lines.append("\t\t\t</Apron>")
    lines.append("\t\t\t" + END)
    nl = "\r\n" if "\r\n" in text_clean else "\n"
    i = text_clean.index("</Aprons>")
    i = text_clean.rindex(nl, 0, i) + len(nl)
    CYXD.write_text(text_clean[:i] + nl.join(lines) + nl + text_clean[i:], encoding="utf-8", newline="")
    print("written", len(out), "door aprons")


if __name__ == "__main__":
    main()
