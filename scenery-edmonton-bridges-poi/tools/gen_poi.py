"""Write the POI marker scenery for every structure boxed in docs/edmonton-bridges/PRIORITY.md.

One <LandmarkLocation type="POI"> per structure code, name = the code (e.g. H2).  A box is a "- [ ]" or "- [x]" line in sections
1-5, 7 and 8 (section 6 is the excluded set and section 9 is "do not model").  Codes are the bold ones at the start of the line (plus
the "with T131" style stations).  Centres come from docs/edmonton-bridges/draw-map.py, else from "Centre lat, lon" text in the box line.
Ground altitude: the bridges project's placements.json where the code has a site, else GROUND_DEFAULT.

    python -I scenery-edmonton-bridges-poi/tools/gen_poi.py
"""
import importlib.util
import json
import re
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PRIORITY = ROOT / "docs/edmonton-bridges/PRIORITY.md"
OUT = ROOT / "scenery-edmonton-bridges-poi/PackageSources/Scenery/edmonton-bridges-poi/edmonton-bridges-poi.xml"
PLACEMENTS = ROOT / "scenery-edmonton-bridges/tools/placements.json"
NS = uuid.UUID("5d0c6c7e-0c1d-4a53-9b6e-0c7d00000004")
GROUND_DEFAULT = 650.0   # m, Edmonton is 600-750; markers use `offset` above this
OFFSET = 40.0            # m, marker height
SHOW_DIST = 20000.0      # m
OWNER = "Cardboard_GT"
# Centres with no source in the docs/catalogue: found or estimated 2026-10-19 (approximate; survey before modelling).
EXTRA = {
    "B264": (53.52410, -113.45710),   # TELUS building: on 83 Street between B263 and B265 (estimated from those two)
    "B267": (53.38480, -113.06960),   # 25, 51069 Range Road 215: OSM road way 31849128, Strathcona County (midpoint of road)
    "B274": (53.54350, -113.48600),   # Chinatown Gates: 97 Street at 102 Avenue (estimated from the Canada Place / Convention Centre ways)
}
CODE = re.compile(r"\b([A-Z])(\d{1,3})\b")
SECTIONS = {1, 2, 3, 4, 5, 6, 7, 8, 9}


def catalogue():
    spec = importlib.util.spec_from_file_location("draw_map", ROOT / "docs/edmonton-bridges/draw-map.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    cat = {}
    for row in (*m.RIVER, *m.FREEWAY, *m.SKIPPED, *m.LRT_STRUCTURES, *m.LRT_STATIONS):
        cat[row[0]] = (row[2], row[3])
    return cat


def boxes(include_excluded):
    sec = 0
    for line in PRIORITY.read_text(encoding="utf-8").splitlines():
        h = re.match(r"## (\d+)\.", line)
        if h:
            sec = int(h.group(1))
            continue
        if not re.match(r"- \[[ x]\] ", line):
            continue
        if sec in SECTIONS or (include_excluded and sec in (6, 9)):
            yield sec, line


def box_codes(line):
    """Codes in the bold phrases of a box; codes only mentioned in prose ('Not H55') are left out."""
    bold = " ".join(re.findall(r"\*\*(.+?)\*\*", line))
    return [a + b for a, b in CODE.findall(bold)]


def text_centres(line):
    """B-code centres written as 'Centre 53.123456, -113.123456'."""
    m = re.search(r"[Cc]entre (?:to survey, )?(53\.\d+), (-113\.\d+)", line)
    return (float(m.group(1)), float(m.group(2))) if m else None


def main():
    cat = catalogue()
    ground = {}
    for site, parts in json.loads(PLACEMENTS.read_text()).items():
        if site.startswith("_"):
            continue
        code = site.upper()
        for rows in parts.values():
            ground[code] = rows[0][3]
    pts, missing = {}, []
    for _sec, line in boxes(True):
        codes = box_codes(line)
        for c in codes:
            if c in cat:
                pts.setdefault(c, cat[c])
            elif re.match(r"B\d+", c) and len(codes) == 1 and text_centres(line):
                pts.setdefault(c, text_centres(line))
            elif c not in pts:
                missing.append(c)
    # placements.json knows B254..N260 centres
    for site, parts in json.loads(PLACEMENTS.read_text()).items():
        c = site.upper()
        if site.startswith("_") or c in pts:
            continue
        for rows in parts.values():
            pts[c] = (rows[0][1], rows[0][2])
            break
    # every catalogue entry (river, freeway, skipped, LRT structures and stations), including excluded and do-not-model ones
    for c, xy in cat.items():
        pts.setdefault(c, xy)
    for c, xy in EXTRA.items():
        pts.setdefault(c, xy)
    missing = [c for c in dict.fromkeys(missing) if c not in pts]
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<FSData version="9.0">',
             f"\t<!-- generated by scenery-edmonton-bridges-poi/tools/gen_poi.py: {len(pts)} POI markers -->"]
    def key(c):
        return (c[0], int(c[1:]))
    for c in sorted(pts, key=key):
        lat, lon = pts[c]
        alt = ground.get(c, GROUND_DEFAULT)
        gid = "{" + str(uuid.uuid5(NS, c)).upper() + "}"
        lines.append(f'\t<LandmarkLocation instanceId="{gid}" lat="{lat:.8f}" lon="{lon:.8f}" alt="{alt:.3f}" name="{c}" type="POI" '
                     f'offset="{OFFSET:.1f}" owner="{OWNER}" distToShowMarker="{SHOW_DIST:.1f}"/>')
    lines.append("</FSData>")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(pts)} markers -> {OUT}")
    if missing:
        print("NO COORDINATES:", " ".join(missing))


main()
