"""Turn data/measurements.json into reference/<site>/elevation/MEASUREMENTS.md and the master MEASUREMENTS.md. Standard library only."""
import csv, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
res = json.load(open(os.path.join(HERE, "data", "measurements.json")))
M2FT = 3.28084
INTRO = ("Generated by `measure-sites.py` from the 2018 LiDAR clips (CGVD2013 metres). **Rise** = DSM minus DTM: the top surface (deck, rails, traffic) above bare ground. It is **not** the clear height under the deck: "
         "take off the deck depth (about 1 to 2.5 m, unknown per bridge). **Structure run** = the longest stretch of a mapped way whose rise exceeds 3 m, so its length is the measured length of the raised structure, "
         "ends included (the abutment fill counts). **Raised width** = how wide the raised surface at deck level is across the way, every deck and rail at that level side by side, so beside a parallel deck it is the whole structure, not one deck; 1 m pixels, +-1 m. "
         "Chainage is metres along the OSM way from its first node. Closed ways are measured as polygons (roofs and outlines). Profiles every 25 m are in `profiles.csv`.")


def f(v, d=1): return "" if v is None else f"{v:.{d}f}"


def grades(name):
    """Ground profile summary per way (50+ m long), from profiles.csv at 25 m steps: start/end ground, mean and steepest 50 m grade."""
    p = os.path.join(HERE, "reference", name, "elevation", "profiles.csv"); ways = {}
    for row in csv.DictReader(open(p, encoding="utf-8")):
        ways.setdefault((row["part"], row["osm_way"]), []).append((float(row["chainage_m"]), float(row["dtm_m"]), float(row["dsm_m"])))
    out = []
    for (part, wid), pts in ways.items():
        if len(pts) < 3 or pts[-1][0] - pts[0][0] < 50: continue
        g = [(pts[i + 2][1] - pts[i][1]) / (pts[i + 2][0] - pts[i][0]) * 100 for i in range(len(pts) - 2) if pts[i + 2][0] > pts[i][0]]
        if not g: continue
        out.append((part, wid, pts[-1][0], pts[0][1], pts[-1][1], (pts[-1][1] - pts[0][1]) / pts[-1][0] * 100, max(g, key=abs)))
    return out


def site_md(name, r):
    L = ["# Measurements from the LiDAR", "", INTRO, ""]
    runs = [e for e in r["lines"] if "structure_run" in e]
    if runs:
        L += ["## Raised structures along mapped ways", "", "| Part | OSM way | Plan length m | Run from m | to m | Run length m | Rise median m | Rise max m | Ground under, min to max m | Deck top m | Raised width m (median, p10 to p90) |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for e in runs:
            s = e["structure_run"]; w = e.get("raised_width_m")
            L.append(f"| {e['part']} | {e['osm_way']} | {e['plan_length_m']} | {s['from_chainage_m']} | {s['to_chainage_m']} | {s['length_m']} | {s['rise_median']} | {s['rise_max']} | {s['dtm_under_min']} to {s['dtm_under_max']} | {s['dsm_median']} | " + (f"{w['median']} ({w['p10']} to {w['p90']})" if w else "") + " |")
        L.append("")
    if r["polygons"]:
        L += ["## Closed ways (roofs, outlines)", "", "| Part | OSM way | Area m2 | Surface median m | Surface 95th pct m | Surface max m | Ground at the edge m (min to max) | 95th pct above ground m | Max above ground m |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for p in r["polygons"]:
            L.append(f"| {p['part']} | {p['osm_way']} | {p['area_m2']} | {p['dsm_median']} | {p['dsm_p95']} | {p['dsm_max']} | {p['ground_edge_median']} ({p['ground_edge_min']} to {p['ground_edge_max']}) | {p['p95_above_ground']} | {p['max_above_ground']} |")
        L.append("")
    gr = grades(name)
    if gr:
        L += ["## Ground profile of each way (bare earth, 25 m steps)", "", "Grade is rise over run of the DTM; positive climbs toward the way's last node. Where a way crosses a bridge the DTM is the ground below it, so the grade here is the terrain, not the deck: use the deck-top height in the table above for the deck. Full profiles, with the DSM, are in `profiles.csv`.", "",
              "| Part | OSM way | Length m | Ground at first node m | Ground at last node m | Mean grade % | Steepest 50 m grade % |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for part, wid, ln, a, b, mg, sg in gr: L.append(f"| {part} | {wid} | {ln:.0f} | {a:.2f} | {b:.2f} | {mg:+.1f} | {sg:+.1f} |")
        L.append("")
    if not runs and not r["polygons"] and not gr: L.append("No raised structure found along the mapped ways.\n")
    return "\n".join(L)


master = ["# Measurements from the LiDAR, all sites", "", INTRO, "", "One row per raised structure (longest 3 m-rise run on each mapped deck way). Per-site tables, with every way and the closed outlines, are in `reference/<site>/elevation/MEASUREMENTS.md`.", "",
          "| Site | Part | OSM way | Run length m | Rise median m | Rise max m | Ground under m | Raised width m |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
for name, r in res.items():
    open(os.path.join(HERE, "reference", name, "elevation", "MEASUREMENTS.md"), "w", encoding="utf-8").write(site_md(name, r) + "\n")
    for e in r["lines"]:
        if "structure_run" in e and e["group"] == "decks":
            s = e["structure_run"]; w = e.get("raised_width_m")
            master.append(f"| {name} | {e['part']} | {e['osm_way']} | {s['length_m']} | {s['rise_median']} | {s['rise_max']} | {s['dtm_under_min']} to {s['dtm_under_max']} | " + (f"{w['median']}" if w else "") + " |")
open(os.path.join(HERE, "MEASUREMENTS.md"), "w", encoding="utf-8").write("\n".join(master) + "\n")
print("ok")
