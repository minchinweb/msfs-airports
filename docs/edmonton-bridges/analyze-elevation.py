"""Water-surface and deck elevations from the 2018 LiDAR clips (CGVD2013, metres).
Run in the venv with rasterio:  python analyze-elevation.py  -> data/elevation-summary.json
Water surface: modal DTM value among low, flat, mostly-river pixels. Deck: DSM sampled along each deck centreline node
(median and 10/90th percentile), minus the water surface."""
import glob, json, os
import numpy as np, rasterio
from pyproj import Transformer
HERE = os.path.dirname(os.path.abspath(__file__))
t = Transformer.from_crs(4326, 3979, always_xy=True)

def collect(o, out):
    if isinstance(o, dict):
        if "nodes" in o and isinstance(o["nodes"], list): out.append(o)
        for v in o.values(): collect(v, out)
    elif isinstance(o, list):
        for v in o: collect(v, out)

def densify(nodes, step=3.0):
    pts = [t.transform(lon, lat) for lat, lon in nodes]
    out = []
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        n = max(1, int(np.hypot(x1 - x0, y1 - y0) / step))
        out += [(x0 + (x1 - x0) * k / n, y0 + (y1 - y0) * k / n) for k in range(n)]
    return out + [pts[-1]]

res = {}
for folder in sorted(set(os.path.dirname(f) for f in glob.glob(os.path.join(HERE, "reference", "**", "geometry.json"), recursive=True))):
    name = os.path.relpath(folder, os.path.join(HERE, "reference")).replace("\\", "/")
    dtm_p, dsm_p = [os.path.join(folder, "elevation", f"{k}-2018-1m.tif") for k in ("dtm", "dsm")]
    if not os.path.exists(dsm_p): continue
    with rasterio.open(dtm_p) as a, rasterio.open(dsm_p) as b:
        dtm = a.read(1, masked=True); dsm = b.read(1, masked=True)
        # water: histogram of DTM values rounded to 0.1 m, look at the lowest 6 m of terrain
        v = dtm.compressed(); lo = np.percentile(v, 0.5)
        sel = v[(v < lo + 6)]
        h, e = np.histogram(sel, bins=np.arange(sel.min(), sel.max() + 0.1, 0.1))
        k = int(h.argmax()); water = float(round((e[k] + e[k + 1]) / 2, 2)); wpix = int(h[k] + (h[k - 1] if k else 0) + (h[k + 1] if k + 1 < len(h) else 0))
        entry = {"dem_min_m": float(round(v.min(), 2)), "water_surface_mode_m": water, "water_pixels_within_0.1m": wpix, "decks": []}
        ds = []; collect(json.load(open(os.path.join(folder, "geometry.json"))), ds)
        for d in ds:
            vals = []
            for x, y in densify(d["nodes"]):
                r, c = b.index(x, y)
                if 0 <= r < dsm.shape[0] and 0 <= c < dsm.shape[1] and not dsm.mask[r, c]: vals.append(float(dsm[r, c]))
            if len(vals) > 5:
                p = np.percentile(vals, [10, 50, 90])
                entry["decks"].append({"part": d.get("part") or d.get("which", "")[:60], "samples": len(vals), "dsm_p10": round(p[0], 2), "dsm_median": round(p[1], 2), "dsm_p90": round(p[2], 2),
                                       "median_above_water_m": round(p[1] - water, 2)})
        res[name] = entry
        print(name, "water", water, "pix", wpix, "min", entry["dem_min_m"], [(x["part"][:22], x["dsm_median"], x["median_above_water_m"]) for x in entry["decks"]][:6])
json.dump(res, open(os.path.join(HERE, "data", "elevation-summary.json"), "w"), indent=1)

# ---- per-site README.md in elevation/ and the master table ELEVATION.md ----
M2FT = 3.28084
def ft(v): return f"{v * M2FT:,.1f}"
LOW_CLIP = 20000  # fewer flat water pixels than this: the clip is not centred on the river, do not trust the water figure
lines = ["# Deck and river elevations from the 2018 LiDAR", "",
         "Generated by `analyze-elevation.py` from the clips in `reference/<site>/elevation/` (NRCan HRDEM / City of Edmonton 2018, 1 m, CGVD2013 orthometric metres). Read `RIVER-LEVEL.md` first for what the river figure means and how to turn it into a gauge stage.", "",
         "River surface = the commonest flat DTM height in the clip's lowest 6 m. It is only valid where the clip holds a river reach (`valid` column). Deck height = median DSM height along the OSM deck centreline in `geometry.json` (the DSM sees the top of the road, rails and any catenary or vehicles near the line, so it can read 0.1 to 1 m high; the 10th to 90th percentile spread is in `data/elevation-summary.json`). **A deck under another deck is invisible to the DSM**: along the High Level lower road the DSM reads the upper deck (662.3 m), so use the handoff offsets from the upper deck for the lower road. For a building row the figure is the roof, not a deck. A 2018 surface is not a design drawing: bridges rebuilt since (Walterdale 2017 is in, Groat deck 2018-2020 is partly in) may differ.", "",
         "| Site | River surface m (valid) | Main deck DSM median m | Above river m | Part used |", "| --- | --- | --- | --- | --- |"]
PICK = ("upper_deck", "road_deck", "lower_road_deck", "lrt_track", "east_track", "road", "pier")
for name, e in res.items():
    ok = e["water_pixels_within_0.1m"] >= LOW_CLIP
    deck = None
    for key in PICK:
        deck = next((d for d in e["decks"] if d["part"].startswith(key)), None)
        if deck: break
    deck = deck or (e["decks"][0] if e["decks"] else None)
    lines.append(f"| {name} | {e['water_surface_mode_m']:.2f} ({'yes' if ok else 'NO'}) | " + (f"{deck['dsm_median']:.2f} | {deck['median_above_water_m']:.2f}{'' if ok else ' (meaningless)'} | {deck['part']}" if deck else "n/a | n/a | n/a") + " |")
    rd = ["# Elevation (2018 LiDAR, CGVD2013)", "",
          f"Files: `dtm-2018-1m.tif` (bare earth), `dsm-2018-1m.tif` (surface incl. bridges, buildings, trees). EPSG:3979, 1 m, float32 metres, nodata -32767. Source: NRCan HRDEM `AB-Edmonton-1m` (City of Edmonton 2018 LiDAR), Open Government Licence - Canada.", "",
          f"River surface in this clip: **{e['water_surface_mode_m']:.2f} m** ({ft(e['water_surface_mode_m'])} ft), " + ("valid." if ok else "NOT valid (the clip has too little river; ignore)."),
          f"Lowest DTM pixel: {e['dem_min_m']:.2f} m.", "", "| Part | Samples | DSM p10 | DSM median | DSM p90 | Median above river |", "| --- | --- | --- | --- | --- | --- |"]
    for d in e["decks"]:
        rd.append(f"| {d['part']} | {d['samples']} | {d['dsm_p10']:.2f} | {d['dsm_median']:.2f} | {d['dsm_p90']:.2f} | {d['median_above_water_m']:.2f}{'' if ok else ' (vs a non-river value)'} |")
    open(os.path.join(HERE, "reference", name, "elevation", "README.md"), "w").write("\n".join(rd) + "\n")
lines += ["", "**Built after the survey, so these rows are not the finished structure:** R14 Tawatina (the 2018 LiDAR predates the bridge; its row is not a deck), P152 (the stop was built on the ground read here), F256 (finished 2018), and T133 and Z125 (the rows show the old bridges that were replaced). See `reference/<site>/OPEN-QUESTIONS.md` and `BLOCKERS.md` section 2.", "", "Measurements derived from the same clips (structure run lengths, rise above the ground under each deck, raised widths, roof heights, ground profiles) are in `MEASUREMENTS.md`."]
open(os.path.join(HERE, "ELEVATION.md"), "w").write("\n".join(lines) + "\n")
